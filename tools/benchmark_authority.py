#!/usr/bin/env python3
"""benchmark_authority.py — render the benchmark authority as a GENERATED view.

The problem this solves. `BENCHMARK-AUTHORITY.md` fuses three incompatible jobs
into one giant markdown table: it is at once the *record* (the single source of
truth for every committed number), the *human reading surface*, and the *machine
parse target* (claim_repro_scorecard.py, bench_provenance.py, docs_scorecard.py,
fresh_status.py all read it). Optimizing one job breaks the others — so single
cells grow to 200-450 words, 40+ rows mix canonical / live / gated / pending /
stale / retracted with no tiering, and neither a human operator nor an agent can
scan it.

The fix is the pattern this repo ALREADY uses for the support-maturity matrix
(docs/HARDWARE-MATRIX.md, regenerated by `fak support-maturity-scorecard
--write-doc`, kept honest by a `--check-doc` freshness gate): separate the RECORD
from the VIEW, and generate the view.

  * RECORD — docs/benchmarks/registry.jsonl: one JSON object per claim with a
    fixed field grammar (id, claim, headline, status, tier, provenance, model,
    baseline, commit, artifact, reproduce, issue, fences[], superseded_by,
    retraction). Structured data, not prose — so fences are a LIST, status is an
    ENUM, and provenance uses bench_provenance's closed vocabulary.
  * VIEW — this generator renders a scannable, tiered markdown from the record:
    a Headline table (quote these), a By-status index, and one compact card per
    claim where the fat prose lives as bullets instead of a wall inside a cell.
  * GATE — `--check` re-renders and diffs against the committed view, so the doc
    can never drift from the record (the same discipline as
    TestSupportMaturityMatrixDocFresh).

The registry now carries the FULL authority (every Quick-Reference + tombstoned
claim, adversarially verified — see docs/benchmarks/AUTHORITY-REDESIGN.md), so
this view is a complete preview of the flip. It does not yet REPLACE the canonical
BENCHMARK-AUTHORITY.md — that swap is the operator's approve-and-flip step,
described in the redesign doc. Pure-stdlib; the only local import is
bench_provenance (the provenance classifier that VALIDATES each row's tag).

Usage::

    python tools/benchmark_authority.py --write docs/benchmarks/AUTHORITY-GENERATED-SAMPLE.md
    python tools/benchmark_authority.py --check docs/benchmarks/AUTHORITY-GENERATED-SAMPLE.md
    python tools/benchmark_authority.py --stdout        # print to stdout

Exit: 0 = clean / wrote / check passed, 1 = check found drift, 2 = bad registry.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any

# The registry is authoritative; bench_provenance is the classifier that a row's
# `provenance` tag is validated against (same closed vocabulary).
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bench_provenance  # noqa: E402

REGISTRY_REL = "docs/benchmarks/registry.jsonl"
DEFAULT_VIEW_REL = "docs/benchmarks/AUTHORITY-GENERATED-SAMPLE.md"
CANONICAL_AUTHORITY_REL = "BENCHMARK-AUTHORITY.md"
CANONICAL_ROW_IDS = ("support-maturity-matrix",)

# Required fields on every registry row. A missing one is a hard error (exit 2) —
# the record must be complete or the view would silently drop a claim.
REQUIRED_FIELDS = (
    "id", "claim", "headline", "status", "tier", "provenance",
    "model", "baseline", "commit", "artifact", "reproduce", "fences",
)

# Closed status vocabulary, in the order the By-status index presents them.
# Each status also carries the one-line meaning shown in the legend.
STATUS_ORDER = ("canonical", "live", "gated", "pending", "stale", "retracted")
STATUS_LEGEND = {
    "canonical": "the number to quote — measured, reconciled, single-source",
    "live":      "a current, committed number backed by a resolvable artifact",
    "gated":     "no number until a named witness lands (claim boundary stated)",
    "pending":   "result packet defined, run not yet collected",
    "stale":     "superseded by a re-measured row — do not cite",
    "retracted": "withdrawn (with the reason recorded) — do not cite",
}
STATUS_EMOJI = {
    "canonical": "🏆", "live": "✅", "gated": "🚧",
    "pending": "⏳", "stale": "🗑", "retracted": "❌",
}

# Provenance is bench_provenance's vocabulary; only `measured` is a real
# wall-clock throughput/latency NUMBER (the rest are floors / witnesses / residue).
PROVENANCE_LEGEND = {
    "measured": "wall-clock throughput/latency measurement",
    "modeled": "closed-form geometry/arithmetic work floor — no wall-clock",
    "functional": "a witness/verdict, NOT a throughput number",
    "unknown": "no resolving evidence yet (pending/gated)",
}
# Compact, UNAMBIGUOUS provenance codes for the headline table. A single-letter
# code fails here: `measured` and `modeled` both start with "m", and collapsing
# those two is the exact defect the provenance discipline exists to prevent.
PROVENANCE_CODE = {
    "measured": "meas", "modeled": "model", "functional": "func", "unknown": "—",
}


class RegistryError(Exception):
    """A structural defect in the registry (missing field, bad enum)."""


def load_registry(path: str) -> list[dict[str, Any]]:
    """Parse registry.jsonl into a list of validated row dicts.

    Raises RegistryError on any structural defect so the caller can exit 2 —
    the record is the source of truth, so a malformed record must fail loudly
    rather than render a lossy view.
    """
    rows: list[dict[str, Any]] = []
    with open(path, encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            raw = raw.strip()
            if not raw:
                continue
            try:
                row = json.loads(raw)
            except json.JSONDecodeError as e:
                raise RegistryError(f"line {lineno}: invalid JSON: {e}") from e
            for field in REQUIRED_FIELDS:
                if field not in row:
                    raise RegistryError(f"line {lineno} ({row.get('id', '?')}): missing field {field!r}")
            if row["status"] not in STATUS_ORDER:
                raise RegistryError(f"{row['id']}: unknown status {row['status']!r} "
                                    f"(want one of {STATUS_ORDER})")
            if row["provenance"] not in bench_provenance.TAGS:
                raise RegistryError(f"{row['id']}: unknown provenance {row['provenance']!r} "
                                    f"(want one of {bench_provenance.TAGS})")
            if not isinstance(row["fences"], list):
                raise RegistryError(f"{row['id']}: fences must be a list")
            rows.append(row)
    ids = [r["id"] for r in rows]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise RegistryError(f"duplicate id(s): {sorted(dupes)}")
    return rows


def _anchor(row_id: str) -> str:
    """The in-doc anchor slug for a claim card (GitHub-style)."""
    return "claim-" + row_id


def _headline_table(rows: list[dict[str, Any]]) -> list[str]:
    """§1 — the scannable one-line-per-claim quote table (tier-1 canonical+live)."""
    picked = [r for r in rows if r["tier"] == 1 and r["status"] in ("canonical", "live")]
    picked.sort(key=lambda r: (r["status"] != "canonical", r["id"]))
    out = [
        "## 1 · Headline numbers — quote these",
        "",
        "One line per claim. The number is the quotable figure; **Prov** is provenance "
        "(`meas` = wall-clock measurement, `model` = geometry/arithmetic floor, `func` = "
        "witness/verdict, `—` = pending/gated); click the claim to jump to its card.",
        "",
        "| Claim | Number | Prov | Status |",
        "|---|---|---|---|",
    ]
    for r in picked:
        prov = PROVENANCE_CODE[r["provenance"]]
        status = f"{STATUS_EMOJI[r['status']]} {r['status']}"
        out.append(f"| [{_md(r['claim'])}](#{_anchor(r['id'])}) "
                   f"| **{_md(r['headline'])}** | {prov} | {status} |")
    out.append("")
    return out


def _status_index(rows: list[dict[str, Any]]) -> list[str]:
    """§2 — the By-status index so live headline numbers separate from dead rows."""
    out = ["## 2 · By status", ""]
    for status in STATUS_ORDER:
        group = [r for r in rows if r["status"] == status]
        if not group:
            continue
        out.append(f"**{STATUS_EMOJI[status]} {status}** ({len(group)}) — "
                   f"{STATUS_LEGEND[status]}")
        out.append("")
        for r in sorted(group, key=lambda r: r["id"]):
            out.append(f"- [{_md(r['claim'])}](#{_anchor(r['id'])}) — "
                       f"{_md(r['headline'])}")
        out.append("")
    return out


def _claim_cards(rows: list[dict[str, Any]]) -> list[str]:
    """§3 — one compact card per claim; the fat prose becomes bullets, not a wall."""
    out = ["## 3 · Claim cards", ""]
    order = {s: i for i, s in enumerate(STATUS_ORDER)}
    for r in sorted(rows, key=lambda r: (r["tier"], order[r["status"]], r["id"])):
        out.append(f"### {r['claim']}")
        out.append(f'<a id="{_anchor(r["id"])}"></a>')
        out.append("")
        out.append(f"> **{_md(r['headline'])}**")
        out.append("")
        out.append(f"- **status** · {STATUS_EMOJI[r['status']]} {r['status']} "
                   f"— {STATUS_LEGEND[r['status']]}")
        out.append(f"- **provenance** · {r['provenance']} "
                   f"— {PROVENANCE_LEGEND[r['provenance']]}")
        out.append(f"- **model** · {_md(r['model'])}")
        out.append(f"- **baseline** · {_md(r['baseline'])}")
        out.append(f"- **commit** · `{_md(r['commit'])}`")
        out.append(f"- **artifact** · `{_md(r['artifact'])}`")
        out.append(f"- **reproduce** · `{_md(r['reproduce'])}`")
        if r.get("issue"):
            out.append(f"- **issue** · [#{r['issue']}](https://github.com/anthony-chaudhary/fak/issues/{r['issue']})")
        if r.get("superseded_by"):
            out.append(f"- **superseded by** · [{r['superseded_by']}](#{_anchor(r['superseded_by'])})")
        if r.get("retraction"):
            out.append(f"- **⚠️ retraction** · {_md(r['retraction'])}")
        if r["fences"]:
            out.append("- **fences**")
            for fence in r["fences"]:
                out.append(f"  - {_md(fence)}")
        out.append("")
    return out


def _md(text: str) -> str:
    """Escape the pipe so a claim/fence with a `|` never breaks a table row."""
    return str(text).replace("|", "\\|")


def render(rows: list[dict[str, Any]]) -> str:
    """Render the whole generated view as a deterministic markdown string.

    Deterministic by construction — no timestamp, no Date.now — so `--check`
    is a pure function of the registry (the freshness gate depends on this).
    """
    counts = {t: sum(1 for r in rows if r["provenance"] == t) for t in bench_provenance.TAGS}
    header = [
        "---",
        'title: "Benchmark Authority - generated view of the record"',
        'description: "A generated, tiered view of fak\'s full benchmark-authority record from registry.jsonl, held in sync with the record by a --check freshness gate."',
        "---",
        "",
        "# Benchmark Authority — generated view (preview of the flip)",
        "",
        "<!-- GENERATED by tools/benchmark_authority.py from docs/benchmarks/registry.jsonl.",
        "     Do not edit by hand — edit the registry and re-run --write. -->",
        "",
        "> **What this is.** A scannable, tiered rendering of the FULL benchmark record "
        "(`docs/benchmarks/registry.jsonl` — every authority claim), generated — not hand-typed. "
        "It previews the redesign in [AUTHORITY-REDESIGN.md](AUTHORITY-REDESIGN.md): the record is "
        "the source of truth, this view is a pure function of it, and a `--check` freshness gate "
        "keeps them from drifting (the same discipline as the support-maturity matrix). The "
        "canonical `BENCHMARK-AUTHORITY.md` is untouched pending the operator's approve-and-flip.",
        "",
        f"> **Provenance mix.** {bench_provenance.summary_line(counts)}. "
        "Only `measured` is a wall-clock number; `modeled` is a work floor, `functional` a "
        "witness/verdict, `unknown` the fail-closed residue (pending/gated).",
        "",
        f"**Claims in the record:** {len(rows)}  ·  "
        f"**source:** `{REGISTRY_REL}`  ·  "
        f"**regenerate:** `python tools/benchmark_authority.py --write {DEFAULT_VIEW_REL}`",
        "",
        "---",
        "",
    ]
    body = _headline_table(rows) + ["---", ""] + _status_index(rows) + ["---", ""] + _claim_cards(rows)
    return "\n".join(header + body).rstrip() + "\n"


def canonical_row(row: dict[str, Any]) -> str:
    """Render the canonical authority-table row for a registry record."""
    return (
        f"| **{_md(row['claim'])}** | **{_md(row['headline'])}** | "
        f"{_md(row['model'])} | {_md(row['baseline'])} | "
        f"{_md(row['commit'])} | {_md(row['artifact'])} — "
        f"Reproduce: `{row['reproduce']}` |"
    )


def check_canonical_rows(root: str, rows: list[dict[str, Any]]) -> list[str]:
    """Return canonical rows that do not match their registry-backed rendering."""
    path = os.path.join(root, CANONICAL_AUTHORITY_REL)
    try:
        with open(path, encoding="utf-8") as f:
            canonical = f.read()
    except FileNotFoundError:
        return [f"missing {CANONICAL_AUTHORITY_REL}"]

    by_id = {row["id"]: row for row in rows}
    stale: list[str] = []
    for claim_id in CANONICAL_ROW_IDS:
        row = by_id.get(claim_id)
        if row is None:
            stale.append(f"registry missing {claim_id}")
        elif canonical_row(row) not in canonical:
            stale.append(claim_id)
    return stale


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--registry", default=None,
                    help=f"registry path (default: <root>/{REGISTRY_REL})")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", metavar="PATH", nargs="?", const=DEFAULT_VIEW_REL,
                   help=f"write the view (default PATH: {DEFAULT_VIEW_REL})")
    g.add_argument("--check", metavar="PATH", nargs="?", const=DEFAULT_VIEW_REL,
                   help="re-render and diff against PATH; exit 1 on drift (freshness gate)")
    g.add_argument("--stdout", action="store_true", help="print the view to stdout")
    args = ap.parse_args(argv)

    root = os.path.abspath(args.root)
    registry = args.registry or os.path.join(root, REGISTRY_REL)

    try:
        rows = load_registry(registry)
    except FileNotFoundError:
        print(f"benchmark-authority: registry not found: {registry}", file=sys.stderr)
        return 2
    except RegistryError as e:
        print(f"benchmark-authority: bad registry: {e}", file=sys.stderr)
        return 2

    view = render(rows)

    if args.check is not None:
        target = args.check if os.path.isabs(args.check) else os.path.join(root, args.check)
        try:
            with open(target, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            print(f"benchmark-authority: check target missing: {target}\n"
                  f"  fix: python tools/benchmark_authority.py --write {args.check}", file=sys.stderr)
            return 1
        if current != view:
            print(f"benchmark-authority: STALE — {args.check} differs from the registry.\n"
                  f"  fix: python tools/benchmark_authority.py --write {args.check}", file=sys.stderr)
            return 1
        stale_canonical = check_canonical_rows(root, rows)
        if stale_canonical:
            ids = ", ".join(stale_canonical)
            print(f"benchmark-authority: STALE — {CANONICAL_AUTHORITY_REL} differs from "
                  f"the registry for: {ids}.\n"
                  f"  fix: reconcile those canonical rows from {REGISTRY_REL}", file=sys.stderr)
            return 1
        print(f"benchmark-authority: fresh — {args.check} and "
              f"{CANONICAL_AUTHORITY_REL} match the registry ({len(rows)} claims).")
        return 0

    if args.write is not None:
        target = args.write if os.path.isabs(args.write) else os.path.join(root, args.write)
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(view)
        print(f"benchmark-authority: wrote {args.write} ({len(rows)} claims).")
        return 0

    sys.stdout.write(view)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
