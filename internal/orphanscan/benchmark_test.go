// createBenchmarkPackage generates a synthetic Go package directory containing
// a realistic mix of exported APIs, wired helpers, orphan funcs, receiver methods,
// compiler/runtime directives, doc keep hatches, and test files.
func createBenchmarkPackage(tb testing.TB, dir string, numFiles, funcsPerFile int) {
	tb.Helper()
	for f := 0; f < numFiles; f++ {
		var sb strings.Builder
		sb.WriteString("package benchpkg\n\n")
		if f == 0 {
			sb.WriteString("func main() {}\nfunc init() {}\nfunc _() {}\n\n")
		}
		for i := 0; i < funcsPerFile; i++ {
			fnID := f*funcsPerFile + i
			switch fnID % 6 {
			case 0:
				// Exported function that calls an unexported helper.
				sb.WriteString(fmt.Sprintf("func ExportedFunc%d() int {\n\treturn wiredHelper%d()\n}\n\n", fnID, fnID))
				sb.WriteString(fmt.Sprintf("func wiredHelper%d() int {\n\treturn %d\n}\n\n", fnID, fnID))
			case 1:
				// True orphan function: unexported, not referenced elsewhere in package.
				sb.WriteString(fmt.Sprintf("func orphanFunc%d() string {\n\treturn \"orphan\"\n}\n\n", fnID))
			case 2:
				// Receiver method on struct (not considered an orphan candidate).
				sb.WriteString(fmt.Sprintf("type Type%d struct{}\n", fnID))
				sb.WriteString(fmt.Sprintf("func (t Type%d) Method%d() {}\n\n", fnID, fnID))
			case 3:
				// Function carrying the //orphanscan:keep suppression escape hatch.
				sb.WriteString("//orphanscan:keep dispatched dynamically via benchmark reflection table\n")
				sb.WriteString(fmt.Sprintf("func keptFunc%d() {}\n\n", fnID))
			case 4:
				// Recursive self-call (conservatively treated as wired use).
				sb.WriteString(fmt.Sprintf("func recursiveFunc%d(n int) int {\n\tif n <= 0 { return 0 }\n\treturn recursiveFunc%d(n-1)\n}\n\n", fnID, fnID))
			case 5:
				// Function exported via Cgo/runtime //export directive.
				sb.WriteString(fmt.Sprintf("//export cExportedFunc%d\n", fnID))
				sb.WriteString(fmt.Sprintf("func cExportedFunc%d() {}\n\n", fnID))
			}
		}

		filename := fmt.Sprintf("file_%d.go", f)
		if f == numFiles-1 {
			// One test file to exercise test-reference scanning
			filename = "file_extra_test.go"
		}
		path := filepath.Join(dir, filename)
		if err := os.WriteFile(path, []byte(sb.String()), 0o644); err != nil {
			tb.Fatalf("write bench file %s: %v", filename, err)
		}
	}

	// Add one generated file to verify generator marker filtering throughput
	genFile := filepath.Join(dir, "zz_generated.go")
	genContent := "// Code generated by benchgen. DO NOT EDIT.\n\npackage benchpkg\n\nfunc genOrphan() {}\n"
	if err := os.WriteFile(genFile, []byte(genContent), 0o644); err != nil {
		tb.Fatalf("write generated bench file: %v", err)
	}
}

// BenchmarkScanDir measures end-to-end directory scanning and orphan detection.
func BenchmarkScanDir(b *testing.B) {
	dir := b.TempDir()
	createBenchmarkPackage(b, dir, 8, 6)

	b.ReportAllocs()
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		orphans, err := ScanDir(dir, "internal/benchpkg")
		if err != nil {
			b.Fatalf("ScanDir failed: %v", err)
		}
		if len(orphans) == 0 {
			b.Fatal("expected orphans to be detected")
		}
	}
}

// BenchmarkScanDirReport measures package scanning with comprehensive report generation
// across small, medium, and large codebases.
func BenchmarkScanDirReport(b *testing.B) {
	for _, tc := range []struct {
		name     string
		numFiles int
		funcs    int
	}{
		{"Small_2Files_10Funcs", 2, 5},
		{"Medium_8Files_48Funcs", 8, 6},
		{"Large_20Files_120Funcs", 20, 6},
	} {
		b.Run(tc.name, func(b *testing.B) {
			dir := b.TempDir()
			createBenchmarkPackage(b, dir, tc.numFiles, tc.funcs)

			b.ReportAllocs()
			b.ResetTimer()
			for i := 0; i < b.N; i++ {
				rep, err := ScanDirReport(dir, "internal/benchpkg")
				if err != nil {
					b.Fatalf("ScanDirReport failed: %v", err)
				}
				if len(rep.Orphans) == 0 {
					b.Fatal("expected orphan findings")
				}
			}
		})
	}
}

