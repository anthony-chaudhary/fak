// BenchmarkParseKeepAllowlist measures parsing throughput across synthetic allowlist
// datasets with varying numbers of entries, comments, and reasons.
func BenchmarkParseKeepAllowlist(b *testing.B) {
	for _, count := range []int{10, 50, 200} {
		b.Run(fmt.Sprintf("%d_entries", count), func(b *testing.B) {
			var sb strings.Builder
			sb.WriteString("# Allowlist benchmark fixture\n\n")
			for i := 0; i < count; i++ {
				if i%5 == 0 {
					sb.WriteString(fmt.Sprintf("# Category comment section %d\n", i))
				}
				sb.WriteString(fmt.Sprintf("internal/pkg%d funcName%d # baseline: migration in progress for entry %d\n", i%15, i, i))
			}
			raw := sb.String()

			b.SetBytes(int64(len(raw)))
			b.ReportAllocs()
			b.ResetTimer()
			for i := 0; i < b.N; i++ {
				entries, err := ParseKeepAllowlist(raw)
				if err != nil {
					b.Fatalf("ParseKeepAllowlist failed: %v", err)
				}
				if len(entries) != count {
					b.Fatalf("got %d entries, want %d", len(entries), count)
				}
			}
		})
	}
}

