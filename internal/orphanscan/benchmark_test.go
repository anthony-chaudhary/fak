// TestBenchmarkOrphanscanRuns validates that the benchmark harness and fixture generation
// execute correctly without errors during regular test suite runs.
func TestBenchmarkOrphanscanRuns(t *testing.T) {
	dir := t.TempDir()
	createBenchmarkPackage(t, dir, 4, 6)

	rep, err := ScanDirReport(dir, "internal/benchpkg")
	if err != nil {
		t.Fatalf("ScanDirReport failed: %v", err)
	}
	if len(rep.Orphans) == 0 {
		t.Fatal("expected orphans to be found in synthetic benchmark package")
	}

	keepEntries, err := KeepAllowlist()
	if err != nil {
		t.Fatalf("KeepAllowlist failed: %v", err)
	}
	if len(keepEntries) == 0 {
		t.Fatal("expected non-empty keep allowlist")
	}

	unexpected, _ := Gate([]string{"internal/benchpkg"}, rep.Orphans, keepEntries)
	if len(unexpected) == 0 {
		t.Fatal("expected unexpected orphans when running against real allowlist")
	}

	hint := SuppressionHint(rep.Orphans[0])
	if !strings.Contains(hint, "wire it, delete it") {
		t.Fatalf("unexpected hint content: %s", hint)
	}
}
