// BenchmarkOrphanDetection_InspectAST measures the core syntactic identifier inspection
// and candidate selection over pre-parsed AST trees in memory.
func BenchmarkOrphanDetection_InspectAST(b *testing.B) {
	dir := b.TempDir()
	createBenchmarkPackage(b, dir, 8, 6)

	entries, err := os.ReadDir(dir)
	if err != nil {
		b.Fatal(err)
	}
	fset := token.NewFileSet()
	type parsedFile struct {
		name      string
		file      *ast.File
		generated bool
	}
	var files []parsedFile
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		src, rerr := os.ReadFile(filepath.Join(dir, e.Name()))
		if rerr != nil {
			b.Fatal(rerr)
		}
		f, perr := parser.ParseFile(fset, filepath.Join(dir, e.Name()), src, parser.ParseComments)
		if perr != nil || f == nil {
			continue
		}
		files = append(files, parsedFile{
			name:      e.Name(),
			file:      f,
			generated: isGenerated(f),
		})
	}

	b.ReportAllocs()
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		refs := make(map[string]int, 128)
		type candidate struct {
			file string
			line int
		}
		candidates := make(map[string]candidate, 64)

		for _, pf := range files {
			ast.Inspect(pf.file, func(n ast.Node) bool {
				if id, ok := n.(*ast.Ident); ok {
					refs[id.Name]++
				}
				return true
			})

			if pf.generated {
				continue
			}
			for _, decl := range pf.file.Decls {
				fn, ok := decl.(*ast.FuncDecl)
				if !ok || fn.Recv != nil {
					continue
				}
				name := fn.Name.Name
				if !isUnexported(name) || name == "main" || name == "init" || name == "_" {
					continue
				}
				if hasKeepDirective(fn) || hasLinkDirective(pf.file, name) {
					continue
				}
				candidates[name] = candidate{file: pf.name, line: fset.Position(fn.Pos()).Line}
			}
		}

		var orphans []Orphan
		for name, c := range candidates {
			if refs[name] <= 1 {
				orphans = append(orphans, Orphan{Name: name, File: c.file, Line: c.line})
			}
		}
		if len(orphans) == 0 {
			b.Fatal("expected detected orphans")
		}
	}
}

// BenchmarkGate measures ratchet gating performance, evaluating allowlist filtering,
// partition sorting, and reconciliation between live orphans and scanned packages.
func BenchmarkGate(b *testing.B) {
	for _, tc := range []struct {
		name       string
		numPkgs    int
		numOrphans int
		numKeep    int
	}{
		{"Small_5Pkgs_20Orphans", 5, 20, 15},
		{"Medium_25Pkgs_100Orphans", 25, 100, 75},
		{"Large_100Pkgs_500Orphans", 100, 500, 300},
	} {
		b.Run(tc.name, func(b *testing.B) {
			scanned := make([]string, tc.numPkgs)
			for i := 0; i < tc.numPkgs; i++ {
				scanned[i] = fmt.Sprintf("internal/pkg%d", i)
			}
			orphans := make([]Orphan, tc.numOrphans)
			for i := 0; i < tc.numOrphans; i++ {
				pkgIdx := i % tc.numPkgs
				orphans[i] = Orphan{
					Name: fmt.Sprintf("orphanFunc%d", i),
					File: fmt.Sprintf("internal/pkg%d/file%d.go", pkgIdx, i%5),
					Line: 10 + (i % 50),
				}
			}
			keep := make([]KeepEntry, tc.numKeep)
			for i := 0; i < tc.numKeep; i++ {
				pkgIdx := i % tc.numPkgs
				keep[i] = KeepEntry{
					Pkg:    fmt.Sprintf("internal/pkg%d", pkgIdx),
					Func:   fmt.Sprintf("orphanFunc%d", i*2),
					Reason: fmt.Sprintf("baseline: known orphan func %d under migration", i),
				}
			}

			b.ReportAllocs()
			b.ResetTimer()
			for i := 0; i < b.N; i++ {
				unexpected, unused := Gate(scanned, orphans, keep)
				if len(unexpected) == 0 && len(unused) == 0 {
					b.Fatal("unexpected empty gate partitions")
				}
			}
		})
	}
}

