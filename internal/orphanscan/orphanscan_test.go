// writeGo drops one .go file into dir.
func writeGo(t *testing.T, dir, name, src string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}

// scanNames scans dir and returns the flagged orphan names, sorted.
func scanNames(t *testing.T, dir string) []string {
	t.Helper()
	orphans, err := ScanDir(dir, "")
	if err != nil {
		t.Fatalf("ScanDir: %v", err)
	}
	var names []string
	for _, o := range orphans {
		names = append(names, o.Name)
	}
	sort.Strings(names)
	return names
}

// TestFlagsOrphanNotWired is the core case: an unexported top-level func with no call
// site is flagged; a sibling that IS called from exported code is not. This is the
// "panel builder written but never added to the registry" shape.
func TestFlagsOrphanNotWired(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "panels.go", `package fixture

// orphanBuilder was authored but never added to the registry.
func orphanBuilder() int { return 1 }

// wiredBuilder is in the registry.
func wiredBuilder() int { return 2 }

// Registry is exported API and references only the wired builder.
func Registry() []int { return []int{wiredBuilder()} }
`)
	got := scanNames(t, dir)
	want := []string{"orphanBuilder"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("orphans = %v, want %v", got, want)
	}
}

// TestSkipsExportedMainInitBlank: exported funcs (API), main, init, and the blank func
// are never candidates even with no visible reference.
func TestSkipsExportedMainInitBlank(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "main.go", `package main

func main()      {}
func init()      {}
func _()         {}
func Exported()  {}
func alsoUnused() {}
`)
	got := scanNames(t, dir)
	want := []string{"alsoUnused"} // only the plain unexported one is an orphan
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("orphans = %v, want %v", got, want)
	}
}

// TestTestFileReferenceCountsAsUse: a helper referenced only from a _test.go file is
// NOT an orphan — a test-only helper is wired, just wired by the tests.
func TestTestFileReferenceCountsAsUse(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "helper.go", `package fixture

func onlyTestUses() int { return 9 }
`)
	writeGo(t, dir, "helper_test.go", `package fixture

// Exercise is exported so it is not itself a candidate; it wires onlyTestUses.
func Exercise() { _ = onlyTestUses() }
`)
	if got := scanNames(t, dir); len(got) != 0 {
		t.Fatalf("orphans = %v, want none (test-referenced helper is wired)", got)
	}
}

