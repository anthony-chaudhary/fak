// TestMethodNotFlagged: a receiver method may satisfy an interface and be dispatched
// dynamically, so methods are out of scope even when their name is unreferenced.
func TestMethodNotFlagged(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "method.go", `package fixture

type T struct{}

func (t T) unusedMethod() {}

func Use() { _ = T{} }
`)
	if got := scanNames(t, dir); len(got) != 0 {
		t.Fatalf("orphans = %v, want none (methods are out of scope)", got)
	}
}

// TestRecursiveSelfCallNotFlagged documents the deliberate conservative false negative:
// a func that only references itself counts as used, so a purely-recursive but
// externally-dead func is NOT flagged. Precision over recall — we never cry wolf.
func TestRecursiveSelfCallNotFlagged(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "recur.go", `package fixture

func recur(n int) int {
	if n <= 0 {
		return 0
	}
	return recur(n - 1)
}
`)
	if got := scanNames(t, dir); len(got) != 0 {
		t.Fatalf("orphans = %v, want none (self-reference is conservatively a use)", got)
	}
}

// TestRelPrefixAndUnparseableFile: relPrefix is applied to File, and a file that will
// not parse is skipped rather than failing the scan.
func TestRelPrefixAndUnparseableFile(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "good.go", `package fixture

func lonely() {}
`)
	writeGo(t, dir, "broken.go", "package fixture\n\nfunc (((( syntax error\n")
	orphans, err := ScanDir(dir, "internal/fixture")
	if err != nil {
		t.Fatalf("ScanDir: %v", err)
	}
	if len(orphans) != 1 || orphans[0].Name != "lonely" {
		t.Fatalf("orphans = %+v, want one 'lonely'", orphans)
	}
	if orphans[0].File != "internal/fixture/good.go" {
		t.Errorf("File = %q, want internal/fixture/good.go", orphans[0].File)
	}
	if orphans[0].Line != 3 {
		t.Errorf("Line = %d, want 3", orphans[0].Line)
	}
}

