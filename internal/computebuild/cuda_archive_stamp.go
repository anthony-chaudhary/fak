package computebuild

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

// CUDAArchiveStampFile is the generated, git-ignored compute file that carries the
// libfakcuda.a digest into Go's build inputs. Go keys a build on source content but not on
// cgo link inputs, so without it a kernel-only change reuses the previously linked binary.
const CUDAArchiveStampFile = "cuda_archive_stamp_gen.go"

// ErrCUDAArchiveStamp refuses a stamp that cannot name the archive it was derived from.
var ErrCUDAArchiveStamp = errors.New("computebuild: CUDA archive stamp")

// nvcc names its host-stub temp file tmpxft_<pid>_<seq> and leaves that name in the object's
// symbol table, so recompiling identical sources changes a few archive bytes. Masking it keeps
// the digest stable across an unchanged rebuild; the replacement has the same length.
var (
	nvccTempName       = regexp.MustCompile(`tmpxft_[0-9a-f]{8}_[0-9a-f]{8}`)
	nvccTempNameMasked = []byte("tmpxft_00000000_00000000")
)

// build_cuda.sh writes the same bytes; TestBuildCUDAScriptWritesTheGoArchiveStamp pins that.
const cudaArchiveStampTemplate = `// Code generated by fak-dev build-cuda or build_cuda.sh; DO NOT EDIT.

//go:build cuda

package compute

// cudaArchiveDigest keys the compute build on libfakcuda.a, a cgo link input Go does not hash.
var cudaArchiveDigest = "%s"
`

// CUDAArchiveDigest returns the sha256 of the archive with nvcc's per-process temp names masked.
func CUDAArchiveDigest(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("%w: read archive: %w", ErrCUDAArchiveStamp, err)
	}
	sum := sha256.Sum256(nvccTempName.ReplaceAll(data, nvccTempNameMasked))
	return hex.EncodeToString(sum[:]), nil
}

// CUDAArchiveStampSource renders the compute stamp for one archive digest.
func CUDAArchiveStampSource(digest string) ([]byte, error) {
	if raw, err := hex.DecodeString(digest); err != nil || len(raw) != sha256.Size || hex.EncodeToString(raw) != digest {
		return nil, fmt.Errorf("%w: digest is not a lowercase sha256 hex string", ErrCUDAArchiveStamp)
	}
	return fmt.Appendf(nil, cudaArchiveStampTemplate, digest), nil
}

// WriteCUDAArchiveStamp stamps pkgDir with the digest of its libfakcuda.a and reports whether
// the stamp changed. An unchanged digest leaves the file untouched, so Go's cache still hits.
func WriteCUDAArchiveStamp(pkgDir, archive string) (string, bool, error) {
	digest, err := CUDAArchiveDigest(archive)
	if err != nil {
		return "", false, err
	}
	src, err := CUDAArchiveStampSource(digest)
	if err != nil {
		return "", false, err
	}
	path := filepath.Join(pkgDir, CUDAArchiveStampFile)
	if current, err := os.ReadFile(path); err == nil && bytes.Equal(current, src) {
		return digest, false, nil
	}
	// A leading dot keeps a concurrent go build from reading the partial file as a source.
	tmp, err := os.CreateTemp(pkgDir, ".cuda-archive-stamp-*")
	if err != nil {
		return "", false, fmt.Errorf("%w: %w", ErrCUDAArchiveStamp, err)
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return "", false, fmt.Errorf("%w: %w", ErrCUDAArchiveStamp, err)
	}
	if _, err := tmp.Write(src); err != nil {
		tmp.Close()
		return "", false, fmt.Errorf("%w: %w", ErrCUDAArchiveStamp, err)
	}
	if err := tmp.Close(); err != nil {
		return "", false, fmt.Errorf("%w: %w", ErrCUDAArchiveStamp, err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return "", false, fmt.Errorf("%w: %w", ErrCUDAArchiveStamp, err)
	}
	return digest, true, nil
}
