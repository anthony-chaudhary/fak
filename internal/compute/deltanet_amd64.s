//go:build amd64

#include "textflag.h"

// func deltaNetStepAVX512(st, qn, kn, vh, od, kvmem, delta *float32, bt, gate float32)
//
// Canonical Qwen GDN geometry is one 128x128 state matrix. Eight ZMM accumulators
// cover its 128 value columns while rows are streamed exactly once per phase.
TEXT ·deltaNetStepAVX512(SB), NOSPLIT, $0-64
	MOVQ st+0(FP), AX
	MOVQ qn+8(FP), BX
	MOVQ kn+16(FP), CX
	MOVQ vh+24(FP), DX
	MOVQ od+32(FP), SI
	MOVQ kvmem+40(FP), DI
	MOVQ delta+48(FP), R8

	// Phase 1: S' = g*S and kvmem = transpose(S')*k. Each accumulator lane
	// preserves the scalar row order; vectorization is across independent columns.
	VMOVSS gate+60(FP), X31
	VBROADCASTSS X31, Z31
	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3
	VXORPS Z4, Z4, Z4
	VXORPS Z5, Z5, Z5
	VXORPS Z6, Z6, Z6
	VXORPS Z7, Z7, Z7
	MOVQ $128, R9

deltanet_decay_loop:
	VMOVSS (CX), X30
	VBROADCASTSS X30, Z30

	VMOVUPS 0(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 0(AX)
	VFMADD231PS Z30, Z24, Z0

	VMOVUPS 64(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 64(AX)
	VFMADD231PS Z30, Z24, Z1

	VMOVUPS 128(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 128(AX)
	VFMADD231PS Z30, Z24, Z2

	VMOVUPS 192(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 192(AX)
	VFMADD231PS Z30, Z24, Z3

	VMOVUPS 256(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 256(AX)
	VFMADD231PS Z30, Z24, Z4

	VMOVUPS 320(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 320(AX)
	VFMADD231PS Z30, Z24, Z5

	VMOVUPS 384(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 384(AX)
	VFMADD231PS Z30, Z24, Z6

	VMOVUPS 448(AX), Z24
	VMULPS Z31, Z24, Z24
	VMOVUPS Z24, 448(AX)
	VFMADD231PS Z30, Z24, Z7

	ADDQ $512, AX
	ADDQ $4, CX
	DECQ R9
	JNZ deltanet_decay_loop

	VMOVUPS Z0, 0(DI)
	VMOVUPS Z1, 64(DI)
	VMOVUPS Z2, 128(DI)
	VMOVUPS Z3, 192(DI)
	VMOVUPS Z4, 256(DI)
	VMOVUPS Z5, 320(DI)
	VMOVUPS Z6, 384(DI)
	VMOVUPS Z7, 448(DI)

	// Phase 2: delta = (v-kvmem)*beta. Keep all eight vectors live for phase 3.
	VMOVSS bt+56(FP), X30
	VBROADCASTSS X30, Z30
	VMOVUPS 0(DX), Z8
	VSUBPS Z0, Z8, Z8
	VMULPS Z30, Z8, Z8
	VMOVUPS Z8, 0(R8)
	VMOVUPS 64(DX), Z9
	VSUBPS Z1, Z9, Z9
	VMULPS Z30, Z9, Z9
	VMOVUPS Z9, 64(R8)
	VMOVUPS 128(DX), Z10
	VSUBPS Z2, Z10, Z10
	VMULPS Z30, Z10, Z10
	VMOVUPS Z10, 128(R8)
	VMOVUPS 192(DX), Z11
	VSUBPS Z3, Z11, Z11
	VMULPS Z30, Z11, Z11
	VMOVUPS Z11, 192(R8)
	VMOVUPS 256(DX), Z12
	VSUBPS Z4, Z12, Z12
	VMULPS Z30, Z12, Z12
	VMOVUPS Z12, 256(R8)
	VMOVUPS 320(DX), Z13
	VSUBPS Z5, Z13, Z13
	VMULPS Z30, Z13, Z13
	VMOVUPS Z13, 320(R8)
	VMOVUPS 384(DX), Z14
	VSUBPS Z6, Z14, Z14
	VMULPS Z30, Z14, Z14
	VMOVUPS Z14, 384(R8)
	VMOVUPS 448(DX), Z15
	VSUBPS Z7, Z15, Z15
	VMULPS Z30, Z15, Z15
	VMOVUPS Z15, 448(R8)

	// Phase 3: S = S' + k*delta and od += transpose(S)*q.
	VMOVUPS 0(SI), Z16
	VMOVUPS 64(SI), Z17
	VMOVUPS 128(SI), Z18
	VMOVUPS 192(SI), Z19
	VMOVUPS 256(SI), Z20
	VMOVUPS 320(SI), Z21
	VMOVUPS 384(SI), Z22
	VMOVUPS 448(SI), Z23
	MOVQ st+0(FP), AX
	MOVQ qn+8(FP), BX
	MOVQ kn+16(FP), CX
	MOVQ $128, R9

deltanet_update_loop:
	VMOVSS (CX), X30
	VBROADCASTSS X30, Z30
	VMOVSS (BX), X31
	VBROADCASTSS X31, Z31

	VMOVUPS 0(AX), Z24
	VFMADD231PS Z30, Z8, Z24
	VMOVUPS Z24, 0(AX)
	VFMADD231PS Z31, Z24, Z16
	VMOVUPS 64(AX), Z24
	VFMADD231PS Z30, Z9, Z24
	VMOVUPS Z24, 64(AX)
	VFMADD231PS Z31, Z24, Z17
	VMOVUPS 128(AX), Z24
	VFMADD231PS Z30, Z10, Z24
	VMOVUPS Z24, 128(AX)
	VFMADD231PS Z31, Z24, Z18
	VMOVUPS 192(AX), Z24
	VFMADD231PS Z30, Z11, Z24
	VMOVUPS Z24, 192(AX)
	VFMADD231PS Z31, Z24, Z19
	VMOVUPS 256(AX), Z24
	VFMADD231PS Z30, Z12, Z24
	VMOVUPS Z24, 256(AX)
	VFMADD231PS Z31, Z24, Z20
	VMOVUPS 320(AX), Z24
	VFMADD231PS Z30, Z13, Z24
	VMOVUPS Z24, 320(AX)
	VFMADD231PS Z31, Z24, Z21
	VMOVUPS 384(AX), Z24
	VFMADD231PS Z30, Z14, Z24
	VMOVUPS Z24, 384(AX)
	VFMADD231PS Z31, Z24, Z22
	VMOVUPS 448(AX), Z24
	VFMADD231PS Z30, Z15, Z24
	VMOVUPS Z24, 448(AX)
	VFMADD231PS Z31, Z24, Z23

	ADDQ $512, AX
	ADDQ $4, BX
	ADDQ $4, CX
	DECQ R9
	JNZ deltanet_update_loop

	VMOVUPS Z16, 0(SI)
	VMOVUPS Z17, 64(SI)
	VMOVUPS Z18, 128(SI)
	VMOVUPS Z19, 192(SI)
	VMOVUPS Z20, 256(SI)
	VMOVUPS Z21, 320(SI)
	VMOVUPS Z22, 384(SI)
	VMOVUPS Z23, 448(SI)
	VZEROUPPER
	RET
