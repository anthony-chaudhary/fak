  FCUDA_TS("k_iq2xs_gemv", dim3((out + 7) / 8, P), k_iq2xs_gemv<<<dim3((out + 7) / 8, P), 256, 0, g_stream>>>(
      (const unsigned char *)dW, dX, dY, out, in, P));
}
