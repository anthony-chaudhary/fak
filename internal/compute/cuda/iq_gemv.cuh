// fcuda_iq_dot8 dots the 8 signed grid magnitudes of one 8-weight group with xs[0..7].
__device__ __forceinline__ float fcuda_iq_dot8(unsigned long long grid, unsigned char signs, const float *xs) {
  const float4 a = *(const float4 *)xs;
  const float4 b = *(const float4 *)(xs + 4);
  const float xv[8] = {a.x, a.y, a.z, a.w, b.x, b.y, b.z, b.w};
  float part = 0.f;
#pragma unroll
  for (int j = 0; j < 8; ++j) {
    float v = (float)((grid >> (8 * j)) & 0xff);
    v = (signs & (1u << j)) ? -v : v;
    part = fmaf(v, xv[j], part);
  }
  return part;
}

// k_iq2xxs_gemv: 66-byte super-block = f16 d + u16 qs[32]. Group ib32 is two u32 words:
// aux0 = 4 grid indices (one byte per 8-weight group), aux1 = 4x7-bit sign codes + 4-bit
// scale in the top nibble; db = d*(0.5+aux1>>28)*0.25.
__global__ void k_iq2xxs_gemv(const unsigned char *W, const float *X, float *Y, int out, int in, int P) {
  const int lane = threadIdx.x & 31;
  const int o = blockIdx.x * 8 + (threadIdx.x >> 5);
  const int t = blockIdx.y;
  if (o >= out || t >= P) return;
  const int ib32 = lane >> 2, l = lane & 3;
  const int nsb = in / 256;
  const unsigned char *wrow = W + (size_t)o * nsb * 66;
  const float *xrow = X + (size_t)t * in + lane * 8;
  float sum = 0.f;
  for (int sb = 0; sb < nsb; ++sb) {
    const unsigned char *blk = wrow + (size_t)sb * 66;
    const unsigned short *qs = (const unsigned short *)(blk + 2);
    const float d = __half2float(*(const __half *)blk);
    const unsigned char gidx = blk[2 + 8 * ib32 + l];
    const unsigned int aux1 = (unsigned int)qs[4 * ib32 + 2] | ((unsigned int)qs[4 * ib32 + 3] << 16);
    const float db = d * (0.5f + (float)(aux1 >> 28)) * 0.25f;
    const unsigned char signs = fcuda_ksigns_iq2xs[(aux1 >> (7 * l)) & 127];
    sum = fmaf(db, fcuda_iq_dot8(fcuda_iq2xxs_grid[gidx], signs, xrow + (size_t)sb * 256), sum);
  }
#pragma unroll
  for (int delta = 16; delta > 0; delta >>= 1) sum += __shfl_down_sync(0xffffffff, sum, delta);
  if (lane == 0) Y[(size_t)t * out + o] = sum;
}

// k_iq2xs_gemv: 74-byte super-block = f16 d + u16 qs[32] + u8 scales[8]. Each u16 is a
// 9-bit grid index + 7-bit sign code; groups l=0,1 use the low scale nibble, l=2,3 the high.
__global__ void k_iq2xs_gemv(const unsigned char *W, const float *X, float *Y, int out, int in, int P) {
  const int lane = threadIdx.x & 31;
  const int o = blockIdx.x * 8 + (threadIdx.x >> 5);
  const int t = blockIdx.y;
  if (o >= out || t >= P) return;
  const int ib32 = lane >> 2, l = lane & 3;
  const int nsb = in / 256;
  const unsigned char *wrow = W + (size_t)o * nsb * 74;
  const float *xrow = X + (size_t)t * in + lane * 8;
  float sum = 0.f;
  for (int sb = 0; sb < nsb; ++sb) {
    const unsigned char *blk = wrow + (size_t)sb * 74;
    const float d = __half2float(*(const __half *)blk);
    const unsigned short q = ((const unsigned short *)(blk + 2))[4 * ib32 + l];
    const unsigned char sc = blk[66 + ib32];
    const float db = d * (0.5f + (float)(l < 2 ? (sc & 0x0f) : (sc >> 4))) * 0.25f;
    sum = fmaf(db, fcuda_iq_dot8(fcuda_iq2xs_grid[q & 511], fcuda_ksigns_iq2xs[q >> 9], xrow + (size_t)sb * 256), sum);
  }
#pragma unroll
  for (int delta = 16; delta > 0; delta >>= 1) sum += __shfl_down_sync(0xffffffff, sum, delta);
  if (lane == 0) Y[(size_t)t * out + o] = sum;
}

extern "C" void fcuda_iq2xxs_gemv(const uint8_t *dW, const float *dX, float *dY, int out, int in, int P) {
  FCUDA_TS("k_iq2xxs_gemv", dim3((out + 7) / 8, P), k_iq2xxs_gemv<<<dim3((out + 7) / 8, P), 256, 0, g_stream>>>(
      (const unsigned char *)dW, dX, dY, out, in, P));
}

