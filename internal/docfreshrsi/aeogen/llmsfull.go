package aeogen

import (
	"errors"
	"fmt"
	"io"
	"os"
	"regexp"
	"strings"
)

const (
	repoBlobBase = "https://github.com/anthony-chaudhary/fak/blob/main/"
	repoTreeBase = "https://github.com/anthony-chaudhary/fak/tree/main/"
)

var mdLinkRE = regexp.MustCompile(`\[([^\]]+)\]\(([^)]+)\)`)

// LLMSTarget is one local .md document llms.txt links to, in first-link order.
type LLMSTarget struct {
	Title   string
	RelPath string
}

func readVersion(root string) (string, error) {
	v, err := readText(pyJoin(root, "VERSION"))
	if err != nil {
		if errors.Is(err, errInvalidUTF8) {
			return "", err
		}
		return "unknown", nil
	}
	return pyStrip(v), nil
}

func collectTargets(root, indexText string, warn io.Writer) []LLMSTarget {
	seen := map[string]bool{}
	var out []LLMSTarget
	for _, m := range mdLinkRE.FindAllStringSubmatch(indexText, -1) {
		title, target := m[1], m[2]
		if hasAnyPrefix(target, "http://", "https://", "#", "mailto:") {
			continue
		}
		relpath, _, _ := strings.Cut(target, "#")
		if !strings.HasSuffix(relpath, ".md") {
			continue
		}
		if !isFile(pyJoin(root, relpath)) {
			fmt.Fprintf(warn, "warn: linked file not found, skipping: %s\n", relpath)
			continue
		}
		if seen[relpath] {
			continue
		}
		seen[relpath] = true
		out = append(out, LLMSTarget{Title: pyStrip(title), RelPath: strings.ReplaceAll(relpath, `\`, "/")})
	}
	return out
}

func hasAnyPrefix(s string, prefixes ...string) bool {
	for _, p := range prefixes {
		if strings.HasPrefix(s, p) {
			return true
		}
	}
	return false
}

func splitLinkTarget(target string) (string, string) {
	cut := len(target)
	for _, marker := range []string{"#", "?"} {
		if i := strings.Index(target, marker); i != -1 && i < cut {
			cut = i
		}
	}
	return target[:cut], target[cut:]
}

func repoURL(rel string, isDir bool) string {
	base := repoBlobBase
	if isDir {
		base = repoTreeBase
	}
	return base + urlQuote(strings.ReplaceAll(rel, `\`, "/"), "/:@")
}

// absolutizeLocalLinks rewrites local links in an inlined document to repo-absolute
// URLs: once inlined into the flat corpus a relative link has lost its base directory.
func absolutizeLocalLinks(root, text, sourceRelpath string, kinds pathKinds) string {
	sourceDir := posixDirname(sourceRelpath)
	var sb strings.Builder
	last := 0
	for _, m := range mdLinkRE.FindAllStringSubmatchIndex(text, -1) {
		sb.WriteString(text[last:m[0]])
		sb.WriteString(absolutizeLink(root, sourceDir, kinds, text[m[0]:m[1]], text[m[2]:m[3]], text[m[4]:m[5]]))
		last = m[1]
	}
	sb.WriteString(text[last:])
	return sb.String()
}

func absolutizeLink(root, sourceDir string, kinds pathKinds, whole, label, rawTarget string) string {
	target := pyStrip(rawTarget)
	if hasAnyPrefix(target, "http://", "https://", "mailto:", "tel:", "#") {
		return whole
	}
	pathPart, suffix := splitLinkTarget(target)
	if pathPart == "" {
		return whole
	}
	var rel string
	if strings.HasPrefix(pathPart, "/") {
		rel = posixNormpath(strings.TrimLeft(pathPart, "/"))
	} else {
		joined := pathPart
		if sourceDir != "" {
			joined = strings.TrimRight(sourceDir, "/") + "/" + pathPart
		}
		rel = posixNormpath(joined)
	}
	if strings.HasPrefix(rel, "..") {
		return whole
	}
	switch kinds.of(pyJoin(root, rel)) {
	case kindDir:
		return "[" + label + "](" + repoURL(rel, true) + suffix + ")"
	case kindFile:
		return "[" + label + "](" + repoURL(rel, false) + suffix + ")"
	}
	return whole
}

type pathKind int

const (
	kindMissing pathKind = iota
	kindDir
	kindFile
)

// pathKinds memoizes stat results: the corpus repeats the same link targets thousands of
// times and a stat is a costly syscall on Windows.
type pathKinds map[string]pathKind

func (k pathKinds) of(p string) pathKind {
	if v, ok := k[p]; ok {
		return v
	}
	v := kindMissing
	if st, err := os.Stat(p); err == nil {
		switch {
		case st.IsDir():
			v = kindDir
		case st.Mode().IsRegular():
			v = kindFile
		}
	}
	k[p] = v
	return v
}

// BuildLLMSFull renders llms-full.txt for root; warnings about missing linked files go to warn.
func BuildLLMSFull(root string, warn io.Writer) (string, []LLMSTarget, error) {
	indexText, err := readText(pyJoin(root, "llms.txt"))
	if err != nil {
		return "", nil, err
	}
	targets := collectTargets(root, indexText, warn)
	ver, err := readVersion(root)
	if err != nil {
		return "", nil, err
	}
	kinds := pathKinds{}
	parts := []string{
		"# fak — the agent kernel: full documentation corpus",
		"",
		"> This file inlines the full text of every document the curated `llms.txt` " +
			"links to, for one-fetch ingestion by LLMs and answer engines. Generated by " +
			"`tools/gen_llms_full.py` from `llms.txt` (the source of truth). " +
			"Project version: " + ver + ".",
		"",
		"## Index (start with the curated map)",
		"",
		pyStrip(indexText),
		"",
		"---",
		"",
	}
	for _, t := range targets {
		raw, rerr := readTextReplace(pyJoin(root, t.RelPath))
		if rerr != nil {
			return "", nil, rerr
		}
		body := absolutizeLocalLinks(root, pyStrip(raw), t.RelPath, kinds)
		parts = append(parts, "# "+t.Title, "", "> Source: `"+t.RelPath+"`", "", body, "", "---", "")
	}
	return pyRstrip(strings.Join(parts, "\n")) + "\n", targets, nil
}

// RunLLMSFull is `python tools/gen_llms_full.py [--check] --root <root>`: same output
// lines, same exit codes (0 fresh/written, 1 stale/missing/error).
func RunLLMSFull(root string, check bool, stdout, stderr io.Writer) int {
	text, targets, err := BuildLLMSFull(root, stderr)
	if err != nil {
		fmt.Fprintf(stderr, "gen_llms_full: %v\n", err)
		return 1
	}
	out := pyJoin(root, "llms-full.txt")
	if check {
		current, rerr := readText(out)
		if rerr != nil {
			fmt.Fprintln(stdout, "llms-full.txt OUT OF DATE (missing); run: python tools/gen_llms_full.py")
			return 1
		}
		if current != text {
			fmt.Fprintln(stdout, "llms-full.txt OUT OF DATE; run: python tools/gen_llms_full.py")
			return 1
		}
		fmt.Fprintf(stdout, "llms-full.txt up to date (%d documents, %s bytes)\n", len(targets), thousands(runeLen(text)))
		return 0
	}
	if err := writeText(out, text); err != nil {
		fmt.Fprintf(stderr, "gen_llms_full: %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "wrote %s: %d documents, %s bytes\n", out, len(targets), thousands(runeLen(text)))
	return 0
}
