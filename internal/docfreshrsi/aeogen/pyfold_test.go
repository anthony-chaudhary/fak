const pyFoldTablesFile = "pyfoldtables.go"

// pyFoldDeriveScript prints every non-ASCII code point Python's (?i) matches against an
// ASCII letter ("i <cp> <letter>"), every code point casefold() changes ("c <cp> <cps>"),
// and the interpreter's Unicode database version ("v <version>").
const pyFoldDeriveScript = `
import re, sys, unicodedata
pats = [(L, re.compile("(?i)" + L)) for L in "abcdefghijklmnopqrstuvwxyz"]
out = ["v " + unicodedata.unidata_version]
for c in range(0x80, 0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    ch = chr(c)
    for L, p in pats:
        if p.fullmatch(ch):
            out.append("i %x %s" % (c, L))
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    f = chr(c).casefold()
    if f != chr(c):
        out.append("c %x %s" % (c, " ".join("%x" % ord(x) for x in f)))
sys.stdout.write("\n".join(out) + "\n")
`

func parseHexRune(t *testing.T, s string) rune {
	t.Helper()
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		t.Fatalf("bad code point %q: %v", s, err)
	}
	return rune(v)
}

// derivePyFoldTables runs Python once and reduces its output to the two tables the port
// encodes: the IGNORECASE extras, and the casefold entries unicode.ToLower gets wrong.
func derivePyFoldTables(t *testing.T, py string) (map[rune]rune, map[rune]string, string) {
	t.Helper()
	r := runPython(t, py, t.TempDir(), "-I", "-c", pyFoldDeriveScript)
	if r.rc != 0 {
		t.Fatalf("python fold derivation rc=%d: %s", r.rc, r.out)
	}
	ignoreCase := map[rune]rune{}
	folds := map[rune]string{}
	unidata := ""
	sc := bufio.NewScanner(strings.NewReader(r.out))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) == 2 && f[0] == "v" {
			unidata = f[1]
			continue
		}
		if len(f) < 3 {
			continue
		}
		c := parseHexRune(t, f[1])
		switch f[0] {
		case "i":
			ignoreCase[c] = rune(f[2][0])
		case "c":
			var sb strings.Builder
			for _, h := range f[2:] {
				sb.WriteRune(parseHexRune(t, h))
			}
			folds[c] = sb.String()
		}
	}
	exceptions := map[rune]string{}
	for c := rune(0); c <= unicode.MaxRune; c++ {
		if !utf8.ValidRune(c) {
			continue
		}
		want, ok := folds[c]
		if !ok {
			want = string(c)
		}
		if string(unicode.ToLower(c)) != want {
			exceptions[c] = want
		}
	}
	if unidata == "" {
		t.Fatalf("python fold derivation reported no Unicode version: %s", r.out)
	}
	return ignoreCase, exceptions, unidata
}

// unidataOlder reports whether Unicode version a precedes b.
func unidataOlder(t *testing.T, a, b string) bool {
	t.Helper()
	as, bs := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(as) && i < len(bs); i++ {
		x, errA := strconv.Atoi(as[i])
		y, errB := strconv.Atoi(bs[i])
		if errA != nil || errB != nil {
			t.Fatalf("bad Unicode version %q or %q", a, b)
		}
		if x != y {
			return x < y
		}
	}
	return len(as) < len(bs)
}

// pyFoldSkewViolations lists the code points where two exception tables derived from
// different Unicode versions disagree for a reason the version gap cannot explain. Case
// folding of an assigned code point is frozen, so the tables may only disagree where the
// older version still folds the code point to itself, as it does when it is unassigned.
func pyFoldSkewViolations(older, newer map[rune]string) []rune {
	var bad []rune
	for c := rune(0); c <= unicode.MaxRune; c++ {
		oldFold, inOld := older[c]
		newFold, inNew := newer[c]
		if inOld == inNew && oldFold == newFold {
			continue
		}
		if !inOld {
			oldFold = string(unicode.ToLower(c))
		}
		if oldFold != string(c) {
			bad = append(bad, c)
		}
	}
	return bad
}

func renderPyFoldTables(t *testing.T, ignoreCase map[rune]rune, exceptions map[rune]string, unidata string) []byte {
	t.Helper()
	var sb strings.Builder
	sb.WriteString("// Code generated by AEOGEN_UPDATE_FOLD=1 go test -run TestPyFoldTables; DO NOT EDIT.\n\npackage aeogen\n\n")
	fmt.Fprintf(&sb, "// pyFoldUnidataVersion is the Unicode database version of the Python the tables were\n// derived from.\nconst pyFoldUnidataVersion = %q\n\n", unidata)
	sb.WriteString("// pyIgnoreCaseASCII maps each non-ASCII code point Python's re IGNORECASE matches\n// against an ASCII letter to that lowercase letter.\nvar pyIgnoreCaseASCII = map[rune]rune{\n")
	for _, c := range sortedRunes(ignoreCase) {
		fmt.Fprintf(&sb, "0x%04X: '%c',\n", c, ignoreCase[c])
	}
	sb.WriteString("}\n\n// pyCasefoldExceptions holds the code points where str.casefold() differs from\n// unicode.ToLower: full foldings, folds that do not pass through lowercase, and\n// Unicode-version skew between the two runtimes.\nvar pyCasefoldExceptions = map[rune]string{\n")
	for _, c := range sortedRunes(exceptions) {
		fmt.Fprintf(&sb, "0x%04X: %s,\n", c, strconv.QuoteToASCII(exceptions[c]))
	}
	sb.WriteString("}\n")
	out, err := format.Source([]byte(sb.String()))
	if err != nil {
		t.Fatalf("format fold tables: %v", err)
	}
	return out
}

func sortedRunes[V any](m map[rune]V) []rune {
	keys := make([]rune, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys
}

// TestPyFoldTables re-derives the IGNORECASE and casefold tables from Python and fails
// when the committed tables drift; AEOGEN_UPDATE_FOLD=1 rewrites them. A host Python on
// another Unicode version cannot reproduce the casefold table exactly, so there the
// comparison narrows to the code points both versions assign.
func TestPyFoldTables(t *testing.T) {
	py := findPython()
	if py == "" {
		t.Skip("python not on PATH")
	}
	ignoreCase, exceptions, unidata := derivePyFoldTables(t, py)
	if os.Getenv("AEOGEN_UPDATE_FOLD") == "1" {
		if err := os.WriteFile(pyFoldTablesFile, renderPyFoldTables(t, ignoreCase, exceptions, unidata), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if !reflect.DeepEqual(ignoreCase, pyIgnoreCaseASCII) {
		t.Errorf("pyIgnoreCaseASCII drifted from Python: python %v, table %v", ignoreCase, pyIgnoreCaseASCII)
	}
	switch {
	case unidata != pyFoldUnidataVersion:
		older, newer := exceptions, pyCasefoldExceptions
		if unidataOlder(t, pyFoldUnidataVersion, unidata) {
			older, newer = newer, older
		}
		if bad := pyFoldSkewViolations(older, newer); len(bad) > 0 {
			t.Errorf("pyCasefoldExceptions drifted from Python beyond Unicode %s vs %s skew at %U; rerun with AEOGEN_UPDATE_FOLD=1", unidata, pyFoldUnidataVersion, bad)
		} else {
			t.Logf("python has Unicode %s, tables pin %s: compared only code points both assign", unidata, pyFoldUnidataVersion)
		}
	case !reflect.DeepEqual(exceptions, pyCasefoldExceptions):
		t.Errorf("pyCasefoldExceptions drifted from Python (%d derived, %d committed); rerun with AEOGEN_UPDATE_FOLD=1", len(exceptions), len(pyCasefoldExceptions))
	}
	for c := rune(0); c <= unicode.MaxRune; c++ {
		if !utf8.ValidRune(c) {
			continue
		}
		for want := 'a'; want <= 'z'; want++ {
			pyMatch := c < utf8.RuneSelf && unicode.ToLower(c) == want || ignoreCase[c] == want
			if got := pyIgnoreCaseMatchesASCII(c, want); got != pyMatch {
				t.Fatalf("pyIgnoreCaseMatchesASCII(%U, %q) = %v, python %v", c, want, got, pyMatch)
			}
		}
	}
}

func TestPyFoldRegressions(t *testing.T) {
	for q, want := range map[string]bool{
		"İs it fast": true, "ıs it fast": true, "ſhould it run": true,
		"İs it": false, "Knows it": false, "Isİt": false, "İs": true,
	} {
		if got := readsAsQuestion(q); got != want {
			t.Errorf("readsAsQuestion(%q) = %v, want %v", q, got, want)
		}
	}
	for in, want := range map[string]string{
		"Straße": "strasse", "ﬃx": "ffix", "İ": "i̇", "ς": "σ",
		"ſ": "s", "K": "k", "Ꭰ": "Ꭰ", "ꭰ": "Ꭰ", "ẞ": "ss",
	} {
		if got := pyCasefold(in); got != want {
			t.Errorf("pyCasefold(%q) = %q, want %q", in, got, want)
		}
	}
}
