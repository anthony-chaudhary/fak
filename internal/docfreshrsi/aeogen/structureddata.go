var (
	cfgURLRE   = regexp.MustCompile(`(?m)^url:` + pyWS + `*"?([^"\n]+)`)
	cfgBaseRE  = regexp.MustCompile(`(?m)^baseurl:` + pyWS + `*"?([^"\n]+)`)
	cfgDescRE  = regexp.MustCompile(`(?m)^description:` + pyWS + `*>-` + pyWS + `*\n((?:[ \t]+.*\n?)+)`)
	cfgImageRE = regexp.MustCompile(`image:` + pyWS + `*"?([^"\n]+)`)

	faqHeadingRE = regexp.MustCompile(`(?m)^##` + pyWS + `+(.+)$`)
	faqRuleRE    = regexp.MustCompile(`(?m)^---` + pyWS + `*$`)
	mdFenceRE    = regexp.MustCompile("(?s)```.*?```")
	mdLeadRE     = regexp.MustCompile(`(?m)^` + pyWS + `*(?:[>#]+|[-*+]|\p{Nd}+\.)` + pyWS + `+`)
	wsRunRE      = regexp.MustCompile(pyWS + `+`)
	mdLinkTextRE = regexp.MustCompile(`\[([^\]]+)\]\([^)]+\)`)
	mdBoldRE     = regexp.MustCompile(`\*\*([^*]+)\*\*`)
	mdCodeRE     = regexp.MustCompile("`([^`]+)`")
	h1RE         = regexp.MustCompile(`(?m)^#` + pyWS + `+.*$`)

	questionLeads = []string{"how", "what", "why", "when", "where", "who", "which", "is", "are", "can", "does", "do", "should", "will"}
)

// sdInputs holds the repo facts the structured-data blocks derive from.
type sdInputs struct {
	root string
}

func (in sdInputs) path(parts ...string) string {
	p := in.root
	for _, part := range parts {
		p = pyJoin(p, part)
	}
	return p
}

// readOrEmpty is the generator's _read(): a missing/unreadable file reads as "", while
// undecodable bytes stay fatal as they are for the Python.
func readOrEmpty(path string) (string, error) {
	s, err := readText(path)
	if err != nil && !errors.Is(err, errInvalidUTF8) {
		return "", nil
	}
	return s, err
}

type siteFacts struct {
	version, url, description, image string
	keywords                         []string
}

func loadSiteFacts(in sdInputs) (siteFacts, error) {
	var f siteFacts
	ver, err := readOrEmpty(in.path("VERSION"))
	if err != nil {
		return f, err
	}
	f.version = pyStrip(ver)
	if f.version == "" {
		f.version = "unknown"
	}
	cfg, err := readOrEmpty(in.path("docs", "_config.yml"))
	if err != nil {
		return f, err
	}
	u := "https://anthony-chaudhary.github.io"
	if m := cfgURLRE.FindStringSubmatch(cfg); m != nil {
		u = pyStrip(m[1])
	}
	u = strings.TrimRight(u, "/")
	b := "/fak"
	if m := cfgBaseRE.FindStringSubmatch(cfg); m != nil {
		b = pyStrip(m[1])
	}
	f.url = u + b
	if m := cfgDescRE.FindStringSubmatch(cfg); m != nil {
		var lines []string
		for _, line := range pySplitlines(m[1]) {
			if s := pyStrip(line); s != "" {
				lines = append(lines, s)
			}
		}
		f.description = strings.Join(lines, " ")
	} else {
		f.description = "Netra Fused Agent Kernel (`fak`): an in-process, default-deny permission " +
			"gate for AI agents fused with an addressable, bit-exact KV cache, in Go."
	}
	if m := cfgImageRE.FindStringSubmatch(cfg); m != nil {
		f.image = pyStrip(m[1])
	} else {
		f.image = "https://raw.githubusercontent.com/anthony-chaudhary/fak/main/visuals/social-preview.png"
	}
	f.keywords, err = disambiguationKeywords(in.path("docs", "marketing", "disambiguation-terms.json"), keywordLimit)
	return f, err
}

func decodePyJSON(s string) (any, error) {
	dec := json.NewDecoder(strings.NewReader(s))
	dec.UseNumber()
	var v any
	if err := dec.Decode(&v); err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, errors.New("trailing data")
	}
	return v, nil
}

func disambiguationKeywords(path string, limit int) ([]string, error) {
	raw, err := readText(path)
	if err != nil {
		if errors.Is(err, errInvalidUTF8) {
			return nil, err
		}
		return nil, nil
	}
	v, err := decodePyJSON(raw)
	if err != nil {
		return nil, nil
	}
	payload, ok := v.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s: top-level JSON is not an object", path)
	}
	terms, ok := payload["hasDefinedTerm"].([]any)
	if !ok {
		return nil, nil
	}
	var out []string
	seen := map[string]bool{}
	for _, t := range terms {
		term, ok := t.(map[string]any)
		if !ok {
			continue
		}
		var candidates []string
		if name, ok := term["name"].(string); ok {
			candidates = append(candidates, name)
		}
		if kws, ok := term["keywords"].(string); ok {
			for _, k := range strings.Split(kws, ",") {
				candidates = append(candidates, pyStrip(k))
			}
		}
		for _, c := range candidates {
			key := strings.Join(pyFields(c), " ")
			folded := pyCasefold(key)
			if key != "" && !seen[folded] {
				seen[folded] = true
				out = append(out, key)
				if len(out) >= limit {
					return out, nil
				}
			}
		}
	}
	return out, nil
}

// plainAnswer flattens markdown answer prose to plain text. Order matters: fences go
// first, list markers while line starts still exist, then whitespace collapses (joining
// emphasis wrapped across lines) before inline markup is stripped, bold before italic.
func plainAnswer(text string) string {
	text = mdFenceRE.ReplaceAllLiteralString(text, " ")
	text = mdLeadRE.ReplaceAllLiteralString(text, "")
	text = pyStrip(wsRunRE.ReplaceAllLiteralString(text, " "))
	text = mdLinkTextRE.ReplaceAllString(text, "${1}")
	text = mdBoldRE.ReplaceAllString(text, "${1}")
	text = stripDelimited(text, '*', func(b byte) bool { return b == '*' })
	text = stripDelimited(text, '_', isASCIIWordByte)
	text = mdCodeRE.ReplaceAllString(text, "${1}")
	return pyStrip(text)
}

func isASCIIWordByte(b byte) bool {
	return b == '_' || b >= 'a' && b <= 'z' || b >= 'A' && b <= 'Z' || b >= '0' && b <= '9'
}

// stripDelimited removes single-delimiter emphasis: `(?<!G)D([^D]+)D(?!G)` -> group 1,
// where G is the guard class. Go's regexp has no lookaround.
func stripDelimited(s string, delim byte, guard func(byte) bool) string {
	var sb strings.Builder
	last := 0
	for i := 0; i < len(s); {
		if s[i] != delim || (i > 0 && guard(s[i-1])) || i+1 >= len(s) || s[i+1] == delim {
			i++
			continue
		}
		rel := strings.IndexByte(s[i+1:], delim)
		if rel < 0 {
			i++
			continue
		}
		j := i + 1 + rel
		if j+1 < len(s) && guard(s[j+1]) {
			i++
			continue
		}
		sb.WriteString(s[last:i])
		sb.WriteString(s[i+1 : j])
		last = j + 1
		i = j + 1
	}
	sb.WriteString(s[last:])
	return sb.String()
}

func readsAsQuestion(q string) bool {
	if strings.HasSuffix(q, "?") {
		return true
	}
	for _, lead := range questionLeads {
		rest, ok := foldPrefix(q, lead)
		if !ok {
			continue
		}
		r, _ := utf8.DecodeRuneInString(rest)
		if rest == "" || !pyIsWordRune(r) {
			return true
		}
	}
	return false
}

// foldPrefix matches an ASCII lowercase prefix case-insensitively the way Python's
// re IGNORECASE does; Go's simple folding misses some of Python's equivalences.
func foldPrefix(s, prefix string) (string, bool) {
	for _, want := range prefix {
		if s == "" {
			return "", false
		}
		r, size := utf8.DecodeRuneInString(s)
		if !pyIgnoreCaseMatchesASCII(r, want) {
			return "", false
		}
		s = s[size:]
	}
	return s, true
}

// pyIgnoreCaseMatchesASCII reports whether Python's (?i) literal letter want (ASCII
// lowercase) matches r.
func pyIgnoreCaseMatchesASCII(r, want rune) bool {
	if r < utf8.RuneSelf {
		if 'A' <= r && r <= 'Z' {
			r += 'a' - 'A'
		}
		return r == want
	}
	return pyIgnoreCaseASCII[r] == want
}

type faqPair struct{ Q, A string }

func faqPairs(faqMD string) []faqPair {
	body := faqMD
	if strings.HasPrefix(body, "---") {
		if end := indexFrom(body, "\n---", 3); end != -1 {
			body = body[end+4:]
		}
	}
	matches := faqHeadingRE.FindAllStringSubmatchIndex(body, -1)
	var out []faqPair
	for k, m := range matches {
		q := pyStrip(body[m[2]:m[3]])
		stop := len(body)
		if k+1 < len(matches) {
			stop = matches[k+1][0]
		}
		aRaw := body[m[1]:stop]
		if loc := faqRuleRE.FindStringIndex(aRaw); loc != nil {
			aRaw = aRaw[:loc[0]]
		}
		a := plainAnswer(aRaw)
		if !readsAsQuestion(q) || runeLen(a) < 20 {
			continue
		}
		if runeLen(a) > 1200 {
			head := runePrefix(a, 1190)
			if i := strings.LastIndex(head, " "); i >= 0 {
				head = head[:i]
			}
			a = head + " …"
		}
		out = append(out, faqPair{Q: q, A: a})
	}
	return out
}

func indexFrom(s, sub string, from int) int {
	if from > len(s) {
		return -1
	}
	if i := strings.Index(s[from:], sub); i >= 0 {
		return from + i
	}
	return -1
}

