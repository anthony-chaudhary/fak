// Command genshaders indexes the vendored Metal translation units from the repository root.
package main

import (
	"bytes"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

const root = "third_party/inklingmetal/runtime"
const outputDir = root + "/metal"

var (
	localInclude  = regexp.MustCompile(`^\s*#\s*include\s+"([^"]+)"`)
	pragmaOnce    = regexp.MustCompile(`^\s*#\s*pragma\s+once\s*$`)
	systemInclude = regexp.MustCompile(`(?m)^\s*#\s*include\s+<[^>]+>[^\n]*`)
	kernelName    = regexp.MustCompile(`\bkernel\s+void\s+(\w+)\s*\(`)
	hostName      = regexp.MustCompile(`\bhost_name\s*\(([^)]+)\)`)
	quoted        = regexp.MustCompile(`"([^"]*)"`)
)

type part struct {
	path         string
	offset, size int
}
type unit struct {
	path  string
	parts []part
}
type index struct {
	files   map[string][]byte
	entries map[string]int
	units   []unit
}

func (x *index) flatten(path string, seen map[string]bool, parts *[]part) error {
	if seen[path] {
		return nil
	}
	seen[path] = true
	data, ok := x.files[path]
	if !ok {
		var err error
		data, err = os.ReadFile(path)
		if err != nil {
			return err
		}
		x.files[path] = data
	}
	start, offset := 0, 0
	for line := range bytes.SplitAfterSeq(data, []byte{'\n'}) {
		match := localInclude.FindSubmatch(line)
		if match != nil || pragmaOnce.Match(line) {
			if offset > start {
				*parts = append(*parts, part{path, start, offset - start})
			}
			if match != nil {
				name := string(match[1])
				other := filepath.Join(root, name)
				if _, err := os.Stat(other); os.IsNotExist(err) {
					other = filepath.Join(filepath.Dir(path), name)
				}
				if err := x.flatten(other, seen, parts); err != nil {
					return err
				}
			}
			start = offset + len(line)
		}
		offset += len(line)
	}
	if offset > start {
		*parts = append(*parts, part{path, start, offset - start})
	}
	return nil
}

func (x *index) add(path string) error {
	u := unit{path: path}
	if err := x.flatten(path, map[string]bool{}, &u.parts); err != nil {
		return err
	}
	var source bytes.Buffer
	for _, p := range u.parts {
		source.Write(x.files[p.path][p.offset : p.offset+p.size])
	}
	cxx := os.Getenv("CXX")
	if cxx == "" {
		cxx = "clang++"
	}
	// Device framework headers define no exported entry points. The C++
	// preprocessor expands Splash's kernel macros without an offline Metal SDK.
	cmd := exec.Command(cxx, "-x", "c++", "-E", "-P", "-", "-D__METAL_VERSION__=400")
	cmd.Stdin = bytes.NewReader(systemInclude.ReplaceAll(source.Bytes(), nil))
	cmd.Stderr = os.Stderr
	pp, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("preprocess %s: %w", path, err)
	}
	names := make(map[string]bool)
	for _, match := range kernelName.FindAllSubmatch(pp, -1) {
		names[string(match[1])] = true
	}
	for _, match := range hostName.FindAllSubmatch(pp, -1) {
		var name strings.Builder
		for _, q := range quoted.FindAllSubmatch(match[1], -1) {
			name.Write(q[1])
		}
		names[name.String()] = true
	}
	for name := range names {
		if prev, exists := x.entries[name]; exists {
			return fmt.Errorf("kernel %s exported by both %s and %s", name, x.units[prev].path, path)
		}
		x.entries[name] = len(x.units)
	}
	x.units = append(x.units, u)
	return nil
}

func (x *index) write() error {
	var out bytes.Buffer
	out.WriteString("// Generated by internal/inklingmetal/cmd/genshaders. Do not edit.\n#pragma clang diagnostic push\n#pragma clang diagnostic ignored \"-Wc23-extensions\"\n")
	ids := map[string]int{}
	for i, path := range slices.Sorted(maps.Keys(x.files)) {
		ids[path] = i
		rel, err := filepath.Rel(outputDir, path)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "static constexpr unsigned char file%d[] = {\n#embed %q\n};\n", i, filepath.ToSlash(rel))
	}
	out.WriteString("#pragma clang diagnostic pop\n")
	for i, u := range x.units {
		fmt.Fprintf(&out, "static constexpr Slice parts%d[] = {\n", i)
		for _, p := range u.parts {
			fmt.Fprintf(&out, "    {file%d + %d, %d},\n", ids[p.path], p.offset, p.size)
		}
		out.WriteString("};\n")
	}
	out.WriteString("static constexpr Unit units[] = {\n")
	for i, u := range x.units {
		path, err := filepath.Rel(root, u.path)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "    {%q, parts%d, std::size(parts%d)},\n", filepath.ToSlash(path), i, i)
	}
	out.WriteString("};\nstatic constexpr Export exports[] = {\n")
	for _, name := range slices.Sorted(maps.Keys(x.entries)) {
		fmt.Fprintf(&out, "    {%q, %d},\n", name, x.entries[name])
	}
	out.WriteString("};\n")
	return os.WriteFile(filepath.Join(outputDir, "FakShaderIndex.inc"), out.Bytes(), 0644)
}

func run() error {
	x := index{files: map[string][]byte{}, entries: map[string]int{}}
	err := filepath.WalkDir(filepath.Join(outputDir, "kernels"), func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && filepath.Ext(path) == ".metal" {
			return x.add(path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	if err = x.write(); err != nil {
		return err
	}
	fmt.Printf("%d source units, %d files, %d shader function names\n", len(x.units), len(x.files), len(x.entries))
	return nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
