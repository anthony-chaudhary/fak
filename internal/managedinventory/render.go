package managedinventory

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// RenderMarkdown is a pure, deterministic projection of the authored catalog.
func RenderMarkdown(c Catalog) []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "---")
	fmt.Fprintln(&b, "title: \"Managed-agent object portability inventory\"")
	fmt.Fprintln(&b, "description: \"Inventory of managed agent object types and symbolic storage roots.\"")
	fmt.Fprintln(&b, "---")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "<!-- Code generated by go run ./cmd/managedinventory --write; DO NOT EDIT. -->")
	fmt.Fprintln(&b, "# Managed-agent object portability inventory")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "This report is generated from [`managed-agent-objects.json`](managed-agent-objects.json). It inventories managed **object types**, not live instances. Symbolic storage roots deliberately contain no operator paths or credential values.")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "- **Schema:** `%s`\n", c.Schema)
	fmt.Fprintf(&b, "- **Search revision:** `%s`\n", c.Discovery.Revision)
	fmt.Fprintf(&b, "- **Search scope:** `%s`\n", strings.Join(c.Discovery.Scope, "`, `"))
	fmt.Fprintf(&b, "- **Registered types / inventory rows:** %d / %d\n", len(registrations), len(c.Objects))
	fmt.Fprintln(&b, "- **Reproduce/check:** `go run ./cmd/managedinventory --check`")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "## Reproducible discovery")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "The checker replays these immutable-revision searches and refuses line/file-count drift. The counts are deliberately broad: the inventory rows below deduplicate vocabulary hits into owned object types.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "| Query | Expected lines | Expected files |")
	fmt.Fprintln(&b, "|---|---:|---:|")
	for _, q := range c.Discovery.Queries {
		fmt.Fprintf(&b, "| `%s` | %d | %d |\n", q.ID, q.ExpectedLines, q.ExpectedFiles)
	}
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "Exact commands:")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "```text")
	for _, q := range c.Discovery.Queries {
		fmt.Fprintf(&b, "git grep -n -I -E '%s' %s -- %s\n", q.Pattern, c.Discovery.Revision, strings.Join(q.Paths, " "))
	}
	fmt.Fprintln(&b, "```")
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "## Smallest representative collection for #6589")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "**Types:** `%s`.\n\n", strings.Join(c.RepresentativeCollection.IDs, "`, `"))
	fmt.Fprintln(&b, c.RepresentativeCollection.Rationale)
	fmt.Fprintln(&b)

	objects := append([]Object(nil), c.Objects...)
	sort.Slice(objects, func(i, j int) bool { return objects[i].ID < objects[j].ID })
	counts := map[string]int{}
	for _, o := range objects {
		counts[o.Portability]++
	}
	fmt.Fprintln(&b, "## Status summary")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "- portable: %d\n- partial: %d\n- local-only: %d\n- unknown: %d\n\n", counts["portable"], counts["partial"], counts["local-only"], counts["unknown"])
	fmt.Fprintln(&b, "| Type | Owner/package | Scope | Sensitivity | Status | Smallest portability gap |")
	fmt.Fprintln(&b, "|---|---|---|---|---|---|")
	for _, o := range objects {
		fmt.Fprintf(&b, "| [`%s`](#%s) | `%s` | %s | `%s` | **%s** | %s |\n",
			o.ID, o.ID, o.Owner, escapeCell(o.Scope), o.Sensitivity, o.Portability, escapeCell(o.Gap))
	}
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "## Object details")
	fmt.Fprintln(&b)
	for _, o := range objects {
		fmt.Fprintf(&b, "### %s\n\n", o.ID)
		fmt.Fprintf(&b, "**%s**\n\n", o.Name)
		fmt.Fprintf(&b, "- **Owner/package:** `%s`\n", o.Owner)
		fmt.Fprintf(&b, "- **Scope:** %s\n", o.Scope)
		fmt.Fprintf(&b, "- **Storage roots:** `%s`\n", strings.Join(o.StorageRoots, "`, `"))
		fmt.Fprintf(&b, "- **Identity/version semantics:** %s\n", o.IdentityVersion)
		fmt.Fprintf(&b, "- **Sensitivity:** `%s`\n", o.Sensitivity)
		if len(o.Dependencies) == 0 {
			fmt.Fprintln(&b, "- **Managed-type dependencies:** none")
		} else {
			fmt.Fprintf(&b, "- **Managed-type dependencies:** `%s`\n", strings.Join(o.Dependencies, "`, `"))
		}
		fmt.Fprintf(&b, "- **Lifecycle:** %s\n", o.Lifecycle)
		fmt.Fprintf(&b, "- **Export today:** %s\n", o.Export)
		fmt.Fprintf(&b, "- **Import today:** %s\n", o.Import)
		fmt.Fprintf(&b, "- **Sync today:** %s\n", o.Sync)
		fmt.Fprintf(&b, "- **Portability:** **%s** — %s\n", o.Portability, o.Gap)
		fmt.Fprintf(&b, "- **Grounding:** `%s`\n\n", strings.Join(o.Evidence, "`, `"))
	}

	fmt.Fprintln(&b, "## Drift contract")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "`internal/managedinventory` keeps type registrations separate from inventory rows. Its committed-tree test and `--check` both fail when a registration lacks exactly one row, a row has no registration, a status is outside `portable|partial|local-only|unknown`, discovery counts change, grounding disappears at the recorded revision, or the generated bytes drift.")
	return b.Bytes()
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}
