package inferencetopology

import (
	"fmt"
	"io"
	"strings"
)

func Render(w io.Writer, m Manifest, prose string) error {
	a, err := Analyze(m)
	if err != nil {
		return err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\nAs of %s. Generated by `fak-dev inference-topology render`.\n\n**ANALYTICAL_NOT_MEASURED.** Resource arithmetic under explicit assumptions; no measured GPU scaling claim.\n\n", m.ID, m.AsOf)
	if prose != "" {
		b.WriteString(prose)
		b.WriteString("\n\n")
	}
	for _, r := range a.Scenarios {
		if !r.Fits {
			fmt.Fprintf(&b, "**CAPACITY_INFEASIBLE — %s:** the modeled peak rank exceeds GPU memory. Its timing cells below are arithmetic only; no executable latency is predicted.\n\n", cellLabel(r.Label))
		}
	}
	b.WriteString("## Reproducible resource appendix\n\nAll capacities and traffic use bytes (GB = 10⁹ bytes). Time is milliseconds per decode step for the supplied batch; one step is not one aggregate output token. Per-rank figures describe a peak rank.\n\n")
	b.WriteString("| Scenario | Fits | Resident GB/rank | Weight stream GB/rank/step | KV read GB/rank/step | HBM ms | Compute ms | Ring ms | Extra network ms | Ideal overlap lower bound ms | Serial resource sum ms |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	cell := func(s string) string { return strings.NewReplacer("|", "\\|", "\n", " ", "\r", " ").Replace(s) }
	for _, r := range a.Scenarios {
		fmt.Fprintf(&b, "| %s | %t | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f |\n", cell(r.Label), r.Fits, r.PerRankTotalResidentBytes/1e9, r.PerRank.WeightStreamBytesPerStep/1e9, r.PerRank.KVReadBytesPerStep/1e9, 1000*r.HBMSeconds, 1000*r.ComputeSeconds, 1000*r.RingSeconds, 1000*r.ExtraNetworkSeconds, 1000*r.IdealOverlapLowerBoundSeconds, 1000*r.SerialResourceSumSeconds)
	}
	for i, r := range a.Scenarios {
		s := m.Scenarios[i]
		fmt.Fprintf(&b, "\n### %s\n\nMode: `%s`; participating GPUs: %d; TP group: %d; KV shards: %d. Expected distinct experts/layer under independent uniform routing: %.3f. Dominant modeled resource: %s.\n\n", cell(r.Label), s.Mode, s.Hardware.GPUs, s.Hardware.TPRanks, s.Hardware.KVShards, r.ExpectedDistinctExpertsPerLayer, r.DominantModeledResource)
		for _, v := range s.Assumptions {
			fmt.Fprintf(&b, "- %s\n", v)
		}
		for _, v := range r.Warnings {
			fmt.Fprintf(&b, "- %s\n", v)
		}
	}
	b.WriteString("\n## Claim ledger\n\n")
	for _, c := range m.Claims {
		fmt.Fprintf(&b, "- **%s** [%s, review by %s]: %s Sources: %s. %s\n", c.ID, c.Status, c.ReviewBy, c.Text, strings.Join(c.SourceIDs, ", "), c.Limitations)
	}
	b.WriteString("\n## Source ledger\n\n")
	for _, s := range m.Sources {
		fmt.Fprintf(&b, "- **%s**: [%s](%s) (%s; accessed %s; review by %s", s.ID, s.Title, s.URL, s.Kind, s.Accessed, s.ReviewBy)
		if s.Revision != "" {
			fmt.Fprintf(&b, "; revision %s", s.Revision)
		}
		b.WriteString(").\n")
	}
	b.WriteString("\n## Model limitations\n\n")
	for _, v := range a.Limitations {
		fmt.Fprintf(&b, "- %s\n", v)
	}
	_, err = io.WriteString(w, b.String())
	return err
}

func cellLabel(s string) string { return strings.NewReplacer("\n", " ", "\r", " ").Replace(s) }
