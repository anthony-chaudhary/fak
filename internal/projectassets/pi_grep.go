package projectassets

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

// PiGrepPath is loaded by Pi's existing trusted-project extension discovery.
// Run fak-project-assets sync first, then launch/reload Pi in this project with
// its normal trust decision. This does not install Pi or alter its trust policy.
const PiGrepPath = ".pi/extensions/fak-grep.ts"

func piGrepProject(root string) (bool, error) {
	info, err := os.Lstat(filepath.Join(root, ".pi"))
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !info.IsDir() {
		return true, fmt.Errorf("Pi project asset directory .pi must be a real directory")
	}
	return true, nil
}

func piGrepFile(root string, create bool) (string, error) {
	for _, rel := range []string{".pi", ".pi/extensions"} {
		dir := filepath.Join(root, filepath.FromSlash(rel))
		info, err := os.Lstat(dir)
		if os.IsNotExist(err) && create {
			if err = os.Mkdir(dir, 0755); err != nil {
				return "", err
			}
			continue
		}
		if err != nil {
			return "", err
		}
		if !info.IsDir() {
			return "", fmt.Errorf("Pi project asset directory %s must be a real directory", rel)
		}
	}
	file := filepath.Join(root, filepath.FromSlash(PiGrepPath))
	if info, err := os.Lstat(file); err == nil {
		if !info.Mode().IsRegular() {
			return "", fmt.Errorf("Pi search asset %s must be a regular file", PiGrepPath)
		}
	} else if !os.IsNotExist(err) || !create {
		return "", err
	}
	return file, nil
}

func syncPiGrep(root string) error {
	file, err := piGrepFile(root, true)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(file)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err == nil && bytes.Equal(current, []byte(defaultPiGrep)) {
		return nil
	}
	return os.WriteFile(file, []byte(defaultPiGrep), 0644)
}

func verifyPiGrep(root string) error {
	file, err := piGrepFile(root, false)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	if !bytes.Equal(bytes.ReplaceAll(current, []byte("\r\n"), []byte("\n")), []byte(defaultPiGrep)) {
		return fmt.Errorf("Pi search asset %s is stale; run fak-project-assets sync", PiGrepPath)
	}
	return nil
}

// Independent original implementation against the pinned Pi extension API;
// no operator-local extension or private session text is embedded.
const defaultPiGrep = `// Generated by fak-project-assets sync. Edit internal/projectassets/pi_grep.go.
// Cost advice, not a security boundary. Never rewrites shell commands or tool arguments.
// Pi tool_call contract: earendil-works/pi@c9f4c7b9fcd0f3e6b5bbc35c7c9b6cda35580eb8.
// Project discovery requires Pi's normal project trust; user_bash and builtin grep are untouched.

const broadReason = "FAK_PI_SEARCH_UNBOUNDED: unrestricted rg has an explicit broad root and no finite --max-depth or nonzero --max-filesize. Narrow the path or supply an intentional bound; the original command was not changed.";
const grepReason = "FAK_PI_SEARCH_RECURSIVE_GREP: recursive grep was kept unchanged. Consider rg only if its regex, ignore-file, binary and symlink behavior matches the intended search.";

function shellParts(command) {
  if (command.length > 16384) return null;
  const parts = [];
  let words = [], literalTildes = new Set(), word = "", active = false, literalTilde = false, quote = "", separator = "";
  const flush = () => { if (active) { if (literalTilde) literalTildes.add(words.length); words.push(word); word = ""; active = false; literalTilde = false; } };
  const segment = (next) => { flush(); if (words.length) parts.push({ words, literalTildes, separator }); words = []; literalTildes = new Set(); separator = next; };
  for (let i = 0; i < command.length; i++) {
    const c = command[i];
    if (quote === "'") { if (c === "'") quote = ""; else { if (!word && c === "~") literalTilde = true; word += c; } continue; }
    if (quote === '"') {
      if (c === '"') { quote = ""; continue; }
      if (c === "$" || c === "\x60") return null;
      if (c === "\\") {
        const n = command[++i]; if (n === undefined) return null;
        if (n === "\n") continue;
        word += '"\\$'.includes(n) ? n : "\\" + n; continue;
      }
      if (!word && c === "~") literalTilde = true;
      word += c; continue;
    }
    if (c === "'" || c === '"') { if (word.startsWith("~") && !word.includes("/")) literalTilde = true; active = true; quote = c; continue; }
    if (c === "\\" && command[i + 1] !== undefined) {
      const n = command[++i]; if (n !== "\n") { if ((!word && n === "~") || (word.startsWith("~") && !word.includes("/"))) literalTilde = true; active = true; word += n; } continue;
    }
    if (c === "$" || c === "\x60" || "<>(){}".includes(c)) return null;
    if (c === "#" && !active) { while (i + 1 < command.length && command[i + 1] !== "\n") i++; continue; }
    if (c === ";" || c === "\n") { segment(c); continue; }
    if (c === "&" || c === "|") {
      if (command[i + 1] !== c) return null;
      i++; segment(c + c); continue;
    }
    if (c === " " || c === "\t") { flush(); continue; }
    if (/\s/.test(c)) return null; // CR/NBSP/etc. are not Bash word separators
    if (!word && c === "~" && active) literalTilde = true; // an empty quoted prefix prevents expansion too
    active = true; word += c;
  }
  if (quote || command.endsWith("\\")) return null;
  segment("");
  return parts.length <= 32 ? parts : null;
}

function program(word) { return word.split("/").pop(); }

function normalizedRoot(value, cwd, literalTilde = false) {
  if (typeof value !== "string" || !value || /[*?[\]]/.test(value) || (literalTilde && value.startsWith("~"))) return null;
  // Named-user and directory-stack/PWD tilde forms need shell state we do not infer.
  // Only an entirely unquoted bare ~ prefix is recognized as a home spelling.
  if (value.startsWith("~") && value !== "~" && !value.startsWith("~/")) return null;
  let p = value;
  if (/^[A-Za-z]:[\\/]/.test(p)) p = p.replace(/\\/g, "/");
  if (!p.startsWith("/") && !p.startsWith("~") && !/^[A-Za-z]:\//.test(p)) {
    if (!cwd) return null;
    p = cwd.replace(/\/$/, "") + "/" + p;
  }
  const prefix = p.startsWith("/") ? "/" : (/^[A-Za-z]:\//.test(p) ? p.slice(0, 3) : "");
  const rest = prefix ? p.slice(prefix.length) : p;
  const components = [];
  for (const c of rest.split("/")) {
    if (!c || c === ".") continue;
    if (c === "..") { if (components.length) components.pop(); }
    else components.push(c);
  }
  return prefix + components.join("/");
}

function isBroadRoot(value, cwd, literalTilde = false, projectCwd = null) {
  const p = normalizedRoot(value, cwd, literalTilde);
  if (p === null) return false;
  if (/^~[^/]*$/.test(p) || /^[A-Za-z]:\/?$/.test(p)) return true;
  if (p === "/" || p === "/root" || /^\/(home|Users)(\/[^/]+)?$/.test(p) || /^[A-Za-z]:\/Users\/[^/]+$/i.test(p)) return true;
  // A shallow directory may itself be the deliberately selected Pi project.
  // Do not turn the depth heuristic into a denial of that known project root.
  if (p === normalizedRoot(projectCwd, null)) return false;
  return p.startsWith("/") && p.split("/").filter(Boolean).length <= 1;
}

function rgShape(words, cwd, literalTildes, projectCwd) {
  let unrestricted = false, pattern = false, files = false, options = true;
  let depth = false, size = false;
  const paths = [];
  const noIgnore = new Set(["--no-ignore", "--no-ignore-vcs", "--no-ignore-parent", "--no-ignore-global", "--no-ignore-dot", "--no-ignore-files"]);
  const simple = new Set(["--line-number", "--files-with-matches", "--files-without-match", "--no-messages", "--hidden", "--follow", "--fixed-strings", "--ignore-case", "--smart-case", "--case-sensitive", "--word-regexp", "--only-matching", "--count", "--count-matches", "--quiet", "--stats", "--json", "--vimgrep", "--text", "--binary", "--no-heading", "--heading", "--with-filename", "--no-filename", "--crlf", "--null", "--null-data", "--multiline", "--multiline-dotall", "--pcre2", "--no-unicode", "--invert-match"]);
  const valued = new Set(["--regexp", "--file", "--glob", "--iglob", "--type", "--type-not", "--max-depth", "--max-filesize", "--max-count", "--after-context", "--before-context", "--context", "--encoding", "--threads", "--color", "--colors", "--sort", "--sortr"]);
  for (let i = 1; i < words.length; i++) {
    let w = words[i];
    if (options && w === "--") { options = false; continue; }
    if (options && w.startsWith("--")) {
      const eq = w.indexOf("="), key = eq < 0 ? w : w.slice(0, eq);
      if (noIgnore.has(key) && eq < 0) { unrestricted = true; continue; }
      if (key === "--files" && eq < 0) { files = true; continue; }
      if (simple.has(key) && eq < 0) continue;
      if (!valued.has(key)) return null;
      const v = eq < 0 ? words[++i] : w.slice(eq + 1);
      if (v === undefined) return null;
      if (key === "--regexp" || key === "--file") pattern = true;
      if (key === "--max-depth") { if (!/^\d+$/.test(v)) return null; depth = true; }
      if (key === "--max-filesize") { if (!/^\d+[KMG]?$/.test(v)) return null; size = /[1-9]/.test(v); }
      continue;
    }
    if (options && w.startsWith("-") && w !== "-") {
      for (let j = 1; j < w.length; j++) {
        const f = w[j];
        if (f === "u") { unrestricted = true; continue; }
        if ("nliLHIsoqvwcFSPUz0a".includes(f)) continue;
        if (!"efgtTmABCjE".includes(f)) return null;
        const v = j + 1 < w.length ? w.slice(j + 1) : words[++i];
        if (v === undefined) return null;
        if (f === "e" || f === "f") pattern = true;
        break;
      }
      continue;
    }
    if (!pattern && !files) pattern = true;
    else paths.push({ value: w, literalTilde: literalTildes.has(i) });
  }
  if (!pattern && !files) return null;
  if (!unrestricted || depth || size) return false;
  return paths.length ? paths.some(p => isBroadRoot(p.value, cwd, p.literalTilde, projectCwd)) : !!cwd && isBroadRoot(cwd, null, false, projectCwd);
}

function recursiveGrep(words) {
  for (let i = 1; i < words.length; i++) {
    const w = words[i];
    if (w === "--" || !w.startsWith("-")) return false;
    if (w === "--regexp" || w === "--file") { i++; continue; }
    if (w.startsWith("--regexp=") || w.startsWith("--file=")) continue;
    if (w === "--recursive" || w === "--dereference-recursive") return true;
    if (w.startsWith("--")) continue;
    for (let j = 1; j < w.length; j++) {
      if (w[j] === "r" || w[j] === "R") return true;
      if ("efABCm".includes(w[j])) { if (j + 1 === w.length) i++; break; }
    }
  }
  return false;
}

function decision(command, projectCwd) {
  const parts = shellParts(command);
  if (!parts) return null;
  let cwd = null, warning = false;
  for (const part of parts) {
    const words = part.words, name = program(words[0]);
    const base = part.separator === "&&" ? cwd : null;
    if (name === "cd" && words.length === 2) { cwd = normalizedRoot(words[1], null, part.literalTildes.has(1)); continue; }
    cwd = null;
    if (name === "rg" || name === "rg.exe") {
      if (rgShape(words, base, part.literalTildes, projectCwd) === true) return { code: "FAK_PI_SEARCH_UNBOUNDED", action: "block", reason: broadReason };
    } else if ((name === "grep" || name === "grep.exe") && recursiveGrep(words)) warning = true;
  }
  return warning ? { code: "FAK_PI_SEARCH_RECURSIVE_GREP", action: "warn", reason: grepReason } : null;
}

export default function (pi) {
  let reports = 0;
  const notified = new Set();
  function report(d, ctx) {
    if (reports < 16) {
      reports++;
      try { pi.appendEntry("fak-search-cost", { schema: 1, code: d.code, action: d.action }); } catch {}
    } else if (reports === 16) {
      reports++;
      try { pi.appendEntry("fak-search-cost", { schema: 1, code: "FAK_PI_SEARCH_TELEMETRY_LIMIT", action: "notice" }); } catch {}
    }
    if (!notified.has(d.code)) {
      notified.add(d.code);
      try { ctx.ui.notify(d.reason, "warning"); } catch {}
    }
  }
  pi.on("tool_call", (event, ctx) => {
    try {
      if (event.toolName !== "bash") return;
      if (typeof event.input?.command !== "string") return;
      const d = decision(event.input.command, ctx?.cwd);
      if (!d) return;
      report(d, ctx);
      if (d.action === "block") return { block: true, reason: d.reason };
    } catch {
      report({ code: "FAK_PI_SEARCH_DETECTOR_ERROR", action: "allow", reason: "FAK_PI_SEARCH_DETECTOR_ERROR: cost detector failed open; command was not changed." }, ctx);
    }
  });
}
`
