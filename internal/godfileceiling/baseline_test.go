package godfileceiling

import (
	"os"
	"strings"
	"testing"
)

// Locks the committed artifact to the generator so a hand-edit of baseline.go reds the build.
func TestCommittedBaselineMatchesGenerator(t *testing.T) {
	data, err := os.ReadFile("baseline.go")
	if err != nil {
		t.Fatalf("read baseline.go: %v", err)
	}
	want := FormatBaseline(Baseline)
	if string(data) != want {
		t.Errorf("committed baseline.go differs from FormatBaseline(Baseline); regenerate via MeasureTree->ProposeBaseline->FormatBaseline\ndiff length: got %d bytes, want %d", len(data), len(want))
	}
}

// Mirrors internal/debtlane's isGeneratedArtifact contract (first 1024 bytes must carry both
// markers) so debtlane stops grading the pin map for model hardcoding.
func TestBaselineCarriesGeneratedMarker(t *testing.T) {
	data, err := os.ReadFile("baseline.go")
	if err != nil {
		t.Fatalf("read baseline.go: %v", err)
	}
	head := data
	if len(head) > 1024 {
		head = head[:1024]
	}
	for _, marker := range []string{"Code generated by", "DO NOT EDIT"} {
		if !strings.Contains(string(head), marker) {
			t.Errorf("first 1024 bytes of baseline.go missing %q — debtlane will grade the pin map as first-party code", marker)
		}
	}
}
