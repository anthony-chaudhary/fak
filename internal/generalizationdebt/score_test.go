func TestScanClassifiesSpecificityAndAcceptedDebt(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "internal/a/specific.go", `package a
// fak:generalization-debt accepted_temporary rationale="migration bridge" owner="runtime" exit_gate="remove after registry ships"
func OpenAIBackend() { println("anthropic") }
func GeminiOnly() {}
func llamaCPPOnly() {}
`)
	writeFixture(t, root, "internal/a/bad.go", `package a
// fak:generalization-debt accepted_temporary rationale="" owner="runtime" exit_gate="remove someday"
func BedrockOnly() {}
`)

	report, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	if report.Schema != Schema {
		t.Fatalf("schema=%q", report.Schema)
	}
	if report.Totals != (Totals{Findings: 4, DebtPoints: 40, AccidentalUnaccepted: 3, AcceptedTemporary: 1}) {
		t.Fatalf("totals=%+v", report.Totals)
	}
	bySubject := findingsBySubject(report.Findings)
	assertFinding(t, bySubject["GeminiOnly"], "model_specific", DispositionAccidental, InterestCritical, "compounding", 10)
	assertFinding(t, bySubject["llamaCPPOnly"], "backend_specific", DispositionAccidental, InterestHigh, "accelerating", 8)
	assertFinding(t, bySubject["BedrockOnly"], "provider_specific", DispositionAccidental, InterestCritical, "compounding", 10)

	accepted := bySubject["OpenAIBackend"]
	assertFinding(t, accepted, "provider_specific", DispositionAcceptedTemporary, InterestCritical, "compounding", 12)
	if accepted.Accepted == nil || accepted.Accepted.Rationale != "migration bridge" || accepted.Accepted.Owner != "runtime" || accepted.Accepted.ExitGate != "remove after registry ships" {
		t.Fatalf("accepted metadata=%+v", accepted.Accepted)
	}
	if !reflect.DeepEqual(accepted.Interest.Drivers, []string{"blast_radius", "explicit_retirement_gate", "implementation_specificity", "unsupported_variant_count"}) {
		t.Fatalf("drivers=%v", accepted.Interest.Drivers)
	}
}

func TestGenericAbstractionsScoreZeroWithoutLaunderingSpecificCode(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "generic.go", `package p
type Backend interface{ Run() }
var OpenAIRegistry = map[string]Backend{}
func RegisterOpenAI() {}
func OpenAIConcrete() {
	// Registry migration is planned, but this is still singular today.
	registry := "future"
	_ = registry
}
`)

	report, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(report.Findings) != 1 || report.Findings[0].Subject != "OpenAIConcrete" {
		t.Fatalf("findings=%+v", report.Findings)
	}
	assertFinding(t, report.Findings[0], "provider_specific", DispositionAccidental, InterestCritical, "compounding", 10)
}

