func TestScanJSONAndOrderingAreDeterministic(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "z.go", "package p\nfunc VLLMOnly(){}\n")
	writeFixture(t, root, "a.go", "package p\nfunc ClaudeOnly(){}\n")

	first, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	second, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	firstJSON, _ := json.Marshal(first)
	secondJSON, _ := json.Marshal(second)
	if string(firstJSON) != string(secondJSON) {
		t.Fatalf("JSON differs:\n%s\n%s", firstJSON, secondJSON)
	}
	if first.Findings[0].Path != "a.go" || first.Findings[1].Path != "z.go" {
		t.Fatalf("ordering=%+v", first.Findings)
	}
}

func writeFixture(t *testing.T, root, path, body string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(body), 0644); err != nil {
		t.Fatal(err)
	}
}

func findingsBySubject(findings []Finding) map[string]Finding {
	out := make(map[string]Finding, len(findings))
	for _, finding := range findings {
		out[finding.Subject] = finding
	}
	return out
}

func assertFinding(t *testing.T, finding Finding, kind string, disposition Disposition, band InterestBand, rate string, points int) {
	t.Helper()
	if finding.Subject == "" || finding.Kind != kind || finding.Disposition != disposition || finding.Interest.Band != band || finding.Interest.Rate != rate || finding.DebtPoints != points {
		t.Fatalf("finding=%+v; want kind=%s disposition=%s interest=%s/%s points=%d", finding, kind, disposition, band, rate, points)
	}
}
