func dequantIQ2XXSScalar(out []float32, raw []byte) {
	dequantScalarBlocks(out, raw, qkK, 66, func(out []float32, raw []byte) {
		d := iq12F16At(raw, 0)
		qs := raw[2:66]
		for ib32 := 0; ib32 < qkK/32; ib32++ {
			aux0 := binary.LittleEndian.Uint32(qs[8*ib32:])
			aux1 := binary.LittleEndian.Uint32(qs[8*ib32+4:])
			db := d * (0.5 + float32(aux1>>28)) * 0.25
			for l := 0; l < 4; l++ {
				grid := iq2XXSGrid[byte(aux0>>uint(8*l))]
				signs := ksignsIQ2XS[(aux1>>uint(7*l))&127]
				for j := 0; j < 8; j++ {
					value := float32(byte(grid >> uint(8*j)))
					if signs&(1<<uint(j)) != 0 {
						value = -value
					}
					out[ib32*32+l*8+j] = db * value
				}
			}
		}
	})
}

